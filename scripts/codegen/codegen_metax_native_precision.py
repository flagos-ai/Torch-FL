"""Generate measured MetaX SDK matrix host entries without vendor Torch."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from codegen_ops import schema_to_cpp_name
from native_host_policy import NATIVE_SDK_PRECISION

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "csrc/aten/generated/metax_native_precision_kernels.cc"


def render(policy=None):
    policy = NATIVE_SDK_PRECISION["metax"] if policy is None else policy
    if policy["vendor"] != "metax" or policy["schema_version"] != 1:
        raise ValueError("unsupported MetaX SDK precision policy")
    rows = sorted(policy["operators"], key=lambda row: row["op"])
    if len({row["op"] for row in rows}) != len(rows):
        raise ValueError("duplicate MetaX SDK precision entry")
    functions, bindings, hits = [], [], []
    for index, row in enumerate(rows):
        if (
            row["op"] not in {"mm", "bmm"}
            or row["rank"] != {"mm": 2, "bmm": 3}[row["op"]]
        ):
            raise ValueError("unmeasured MetaX SDK matrix family")
        if row["dtypes"] != ["BFloat16"]:
            raise ValueError("unmeasured MetaX SDK dtype")
        kind, dispatcher = schema_to_cpp_name(row["op"])
        name = "MetaxNative" + row["op"].capitalize()
        functions.append(
            f"at::Tensor {name}(const at::Tensor& self, const at::Tensor& mat2) {{\n"
            f"  ++hits[{index}];\n"
            f'  RECORD_FUNCTION("flagos::metax::{row["op"]}", std::vector<c10::IValue>());\n'
            f"  return metax_precision::Matrix<{row['rank']}>(self, mat2);\n"
            "}\n"
        )
        bindings.append(
            f"REGISTER_IMPL_TO_DISPATCHER({kind}, {dispatcher}, Backend::kMetax, {name})"
        )
        hits.append(f'    result.insert("{row["op"]}", hits[{index}].load());')
    catalog = {
        "policy": policy,
        "policy_sha256": hashlib.sha256(
            json.dumps(policy, sort_keys=True).encode()
        ).hexdigest(),
    }
    return (
        "// Generated by scripts/codegen/codegen_metax_native_precision.py. Do not edit.\n"
        "#if defined(FLAGOS_NATIVE_METAX_VENDOR)\n"
        '#include "ops.h"\n'
        '#include "../backends/flagos/metax_native_precision.h"\n'
        "#include <ATen/record_function.h>\n#include <torch/library.h>\n#include <atomic>\n\n"
        "namespace at::native::flagos {\nnamespace {\n"
        f"std::atomic<int64_t> hits[{len(rows)}]{{}};\n"
        + "\n".join(functions)
        + "\n"
        + "\n".join(bindings)
        + "\n}  // namespace\n\nTORCH_LIBRARY_FRAGMENT(flagos, m) {\n"
        + '  m.def("native_metax_sdk_catalog() -> str", []() {\n'
        + f'    return std::string(R"catalog({json.dumps(catalog, sort_keys=True)})catalog");\n  }});\n'
        + '  m.def("native_metax_sdk_libraries() -> Dict(str, str)", &metax_precision::Libraries);\n'
        + '  m.def("native_metax_sdk_hits() -> Dict(str, int)", []() {\n'
        + "    c10::Dict<std::string, int64_t> result;\n"
        + "\n".join(hits)
        + "\n    return result;\n  });\n}\n}  // namespace at::native::flagos\n#endif\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if OUTPUT.exists() and OUTPUT.read_text() == text:
        print("MetaX native precision entries are current")
    elif args.check:
        raise SystemExit("stale MetaX native precision entries: " + str(OUTPUT))
    else:
        OUTPUT.write_text(text)
        print("MetaX native precision entries generated")


if __name__ == "__main__":
    main()
