"""Generate measured SDK precision routes without vendor Torch."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from codegen_ops import schema_to_cpp_name
from native_host_policy import NATIVE_SDK_PRECISION

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "csrc/aten/generated/metax_native_precision_kernels.cc"
_SDK_VENDORS = {"metax": ("MetaX", "Metax"), "thead": ("T-Head", "Thead")}

NVIDIA_POINTWISE = {
    "PowScalar": "powf(scalar, value)",
    "Reciprocal": "__frcp_rn(value)",
    "Rsqrt": "rsqrtf(value)",
    "Silu": "__fdiv_rn(value, 1.0f + expf(-value))",
}

NVIDIA_CUDA_POINTWISE = """\
// Generated by scripts/codegen/codegen_metax_native_precision.py. Do not edit.
#include "pointwise.h"

#include <cuda_bf16.h>
#include <cuda_runtime.h>

#include <algorithm>
#include <cstdint>

namespace flagos::nvidia {
namespace {

template <PointwiseOp Op>
__device__ float Evaluate(float value, float scalar) {
@expressions@
}

template <PointwiseOp Op, typename T>
__global__ void Pointwise(const T* input, T* output, int64_t count, float scalar) {
  const auto step = int64_t(blockDim.x) * gridDim.x;
  for (auto i = int64_t(blockDim.x) * blockIdx.x + threadIdx.x; i < count; i += step)
    output[i] = T(Evaluate<Op>(float(input[i]), scalar));
}

template <PointwiseOp Op, class T>
void Launch(int blocks, int threads, cudaStream_t stream, const void* input,
            void* output, int64_t size, float scalar) {
  Pointwise<Op><<<blocks, threads, 0, stream>>>(
      static_cast<const T*>(input), static_cast<T*>(output), size, scalar);
}

}  // namespace

cudaError_t LaunchPointwise(PointwiseOp op, bool bf16, const void* input, void* output,
                            int64_t size, float scalar, cudaStream_t stream) {
  constexpr int threads = 256;
  const auto blocks = std::min<int64_t>(65535, (size - 1) / threads + 1);
  if (bf16) {
    Launch<PointwiseOp::Silu, __nv_bfloat16>(blocks, threads, stream, input, output, size, scalar);
  } else {
    switch (op) {
@launches@
    }
  }
  return cudaGetLastError();
}

}  // namespace flagos::nvidia
"""


def render_nvidia_pointwise():
    expressions, launches = [], []
    for name, expression in NVIDIA_POINTWISE.items():
        tag = f"PointwiseOp::{name}"
        expressions.append(f"  if constexpr (Op == {tag}) return {expression};")
        launches.append(
            f"      case {tag}:\n"
            f"        Launch<{tag}, float>(blocks, threads, stream, input, output, size, scalar);\n"
            "        break;"
        )
    return NVIDIA_CUDA_POINTWISE.replace(
        "@expressions@", "\n".join(expressions)
    ).replace("@launches@", "\n".join(launches))


CUDA_BFLOAT16_SILU = """\
// Generated by scripts/codegen/codegen_metax_native_precision.py. Do not edit.
#include <cuda_bf16.h>
#include <cuda_runtime.h>

#include <algorithm>
#include <cstdint>

namespace at::native::flagos::cuda_precision {
namespace {
__global__ void SiluKernel(const __nv_bfloat16* input, __nv_bfloat16* output, int64_t size) {
  const int64_t step = static_cast<int64_t>(blockDim.x) * gridDim.x;
  for (int64_t i = static_cast<int64_t>(blockIdx.x) * blockDim.x + threadIdx.x;
       i < size; i += step) {
    const float value = __bfloat162float(input[i]);
    output[i] = __float2bfloat16_rn(value / (1.0f + expf(-value)));
  }
}
}  // namespace

cudaError_t LaunchSiluBFloat16(const void* input, void* output, int64_t size, cudaStream_t stream) {
  constexpr int threads = 256;
  const int blocks = std::min<int64_t>(65535, (size - 1) / threads + 1);
  SiluKernel<<<blocks, threads, 0, stream>>>(
      static_cast<const __nv_bfloat16*>(input), static_cast<__nv_bfloat16*>(output), size);
  return cudaGetLastError();
}
}  // namespace at::native::flagos::cuda_precision
"""

SILU_BFLOAT16_HOST = """\
  TORCH_CHECK(self.scalar_type() == at::kBFloat16, "native SiLU requires BF16 input");
  const c10::OptionalDeviceGuard device_guard(self.device());
  auto result = at::empty_like(self, {}, c10::MemoryFormat::Preserve);
  const int64_t size = self.numel();
  if (size == 0) return result;

  const auto input = self.is_non_overlapping_and_dense() ? self : self.contiguous();
  auto output = input.strides().equals(result.strides()) ? result : at::empty_like(input);
  const auto stream = reinterpret_cast<cudaStream_t>(GetCurrentStreamForDevice(self.device().index()));
  const auto status = cuda_precision::LaunchSiluBFloat16(
      input.const_data_ptr(), output.mutable_data_ptr(), size, stream);
  TORCH_CHECK(status == cudaSuccess, "native BF16 SiLU launch failed: ", cudaGetErrorString(status));
  ::flagos::native_host::EnqueueTrace::record(reinterpret_cast<uintptr_t>(stream), true);
  if (!output.is_same(result)) result.copy_(output);
  return result;
"""


def render(policy=None, *, vendor="metax"):
    display, name_prefix = _SDK_VENDORS[vendor]
    policy = NATIVE_SDK_PRECISION[vendor] if policy is None else policy
    if policy["vendor"] != vendor or policy["schema_version"] != 1:
        raise ValueError(f"unsupported {display} SDK precision policy")
    rows = sorted(policy["operators"], key=lambda row: row["op"])
    if len({row["op"] for row in rows}) != len(rows):
        raise ValueError(f"duplicate {display} SDK precision entry")
    functions, bindings, hits = [], [], []
    pointwise_headers = pointwise_declaration = ""
    for index, row in enumerate(rows):
        if row["dtypes"] != ["BFloat16"]:
            raise ValueError(f"unmeasured {display} SDK dtype")
        op = row["op"]
        if op in {"mm", "bmm"} and row.get("rank") == {"mm": 2, "bmm": 3}[op]:
            arguments = "const at::Tensor& self, const at::Tensor& mat2"
            body = f"  return {vendor}_precision::Matrix<{row['rank']}>(self, mat2);\n"
        elif vendor == "thead" and op == "silu" and "rank" not in row:
            arguments = "const at::Tensor& self"
            body = SILU_BFLOAT16_HOST
            pointwise_headers = (
                '#include "native_host/enqueue_trace.h"\n'
                "#include <ATen/ops/empty_like.h>\n#include <cuda_runtime_api.h>\n"
            )
            pointwise_declaration = (
                "namespace cuda_precision {\n"
                "cudaError_t LaunchSiluBFloat16(const void*, void*, int64_t, cudaStream_t);\n"
                "}  // namespace cuda_precision\n"
            )
        else:
            raise ValueError(f"unmeasured {display} SDK precision family: {op}")
        kind, dispatcher = schema_to_cpp_name(op)
        name = name_prefix + "Native" + op.capitalize()
        functions.append(
            f"at::Tensor {name}({arguments}) {{\n"
            f"  ++hits[{index}];\n"
            f'  RECORD_FUNCTION("flagos::{vendor}::{op}", std::vector<c10::IValue>());\n'
            + body
            + "}\n"
        )
        bindings.append(
            f"REGISTER_IMPL_TO_DISPATCHER({kind}, {dispatcher}, Backend::k{name_prefix}, {name})"
        )
        hits.append(f'    result.insert("{row["op"]}", hits[{index}].load());')
    catalog = {
        "policy": policy,
        "policy_sha256": hashlib.sha256(
            json.dumps(policy, sort_keys=True).encode()
        ).hexdigest(),
    }
    return (
        "// Generated by scripts/codegen/codegen_metax_native_precision.py. Do not edit.\n"
        f"#if defined(FLAGOS_NATIVE_{vendor.upper()}_VENDOR)\n"
        '#include "ops.h"\n'
        f'#include "../backends/flagos/{vendor}_native_precision.h"\n'
        f"{pointwise_headers}"
        "#include <ATen/record_function.h>\n#include <torch/library.h>\n#include <atomic>\n\n"
        "namespace at::native::flagos {\n"
        f"{pointwise_declaration}namespace {{\n"
        f"std::atomic<int64_t> hits[{len(rows)}]{{}};\n"
        + "\n".join(functions)
        + "\n"
        + "\n".join(bindings)
        + "\n}  // namespace\n\nTORCH_LIBRARY_FRAGMENT(flagos, m) {\n"
        + f'  m.def("native_{vendor}_sdk_catalog() -> str", []() {{\n'
        + f'    return std::string(R"catalog({json.dumps(catalog, sort_keys=True)})catalog");\n  }});\n'
        + f'  m.def("native_{vendor}_sdk_libraries() -> Dict(str, str)", &{vendor}_precision::Libraries);\n'
        + f'  m.def("native_{vendor}_sdk_hits() -> Dict(str, int)", []() {{\n'
        + "    c10::Dict<std::string, int64_t> result;\n"
        + "\n".join(hits)
        + "\n    return result;\n  });\n}\n}  // namespace at::native::flagos\n#endif\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--vendor", choices=(*_SDK_VENDORS, "nvidia"), default="metax")
    args = parser.parse_args()
    if args.vendor == "nvidia":
        path = ROOT / "csrc/native_host/backends/nvidia/generated_pointwise.cu"
        source = render_nvidia_pointwise()
        if path.is_file() and path.read_text() == source:
            return
        if args.check:
            raise SystemExit(f"stale NVIDIA SDK pointwise kernels: {path}")
        path.write_text(source)
        return
    output = OUTPUT.with_name(f"{args.vendor}_native_precision_kernels.cc")
    outputs = {output: render(vendor=args.vendor)}
    if args.vendor == "thead":
        outputs[output.with_name("cuda_bfloat16_silu.cu")] = CUDA_BFLOAT16_SILU
    display = _SDK_VENDORS[args.vendor][0]
    for path, text in outputs.items():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            raise SystemExit(f"stale {display} native precision entry: {path}")
        path.write_text(text)
    action = "are current" if args.check else "generated"
    print(f"{display} native precision entries {action}")


if __name__ == "__main__":
    main()
