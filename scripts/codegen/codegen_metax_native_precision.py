def render_nvidia_pointwise():
    expressions, launches = [], []
    for name, expression in NVIDIA_POINTWISE.items():
        tag = f"PointwiseOp::{name}"
        expressions.append(f"  if constexpr (Op == {tag}) return {expression};")
        launches.append(
            f"      case {tag}:\n"
            f"        Launch<{tag}, float>(blocks, threads, stream, input, output, size, scalar);\n"
            "        break;"
        )
    return NVIDIA_CUDA_POINTWISE.replace(
        "@expressions@", "\n".join(expressions)
    ).replace("@launches@", "\n".join(launches))


