#!/usr/bin/env python3
"""Generate the Iluvatar FlagGems registration list.

``csrc/aten/backends/iluvatar/generated/iluvatar_flaggems_register.inc`` claims
the FlagGems Python ops on PrivateUse1 so that ``backends_iluvatar.conf`` can
route them to the ``flaggems`` backend. Iluvatar also has a vendor-native
``iluvatar_register.inc`` (generated by ``codegen_iluvatar.py``), so unlike a
platform whose whole PrivateUse1 surface is FlagGems, this file is *one half* of
what the platform claims: it is disjoint from the native one, and together they
cover every PrivateUse1 registration Iluvatar has. Without this file every
``flaggems`` route in the conf has no registered slot, and the call reaches the
dispatcher's empty ``kFlagGems`` slot and raises "backend not registered" instead
of falling back to CPU.

The list is ``FLAGGEMS_PYTHON_OPS`` minus ``NATIVE_TRITON_GAPS['iluvatar']``,
minus ``FLAGGEMS_PENDING_NATIVE_OPS`` (for as long as ``iluvatar`` is in
``FLAGGEMS_PENDING_NATIVE_VENDORS``; it is not, so the subtraction is a no-op
unless that changes). Each op is emitted with the wrapper symbol read back from
the CUDA codegen's ``generated/register.inc`` rather than derived from the op
name: ``add.Tensor`` is served by ``WrapperAddTensor`` while
``_adaptive_avg_pool2d`` is served by ``WrapperPrivAdaptiveAvgPool2d``, and only
the generated file knows which is which.

As with the other vendor generators, the pending subtraction is what keeps this
file in step with ``gen_vendor_confs.py``: that script's ``build_all()`` holds
the same set off ``flaggems`` in the confs, so registering an op here that the
conf does not route would add an ``m.impl()`` nothing dispatches to. Both sides
must read the same set.

Usage:
    python3 scripts/codegen/codegen_iluvatar_flaggems.py            # rewrite the .inc
    python3 scripts/codegen/codegen_iluvatar_flaggems.py --check    # exit 1 if stale
"""

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gen_vendor_confs as g  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
VENDOR = "iluvatar"
OUT_INC = REPO / f"csrc/aten/backends/{VENDOR}/generated/{VENDOR}_flaggems_register.inc"
# The CUDA codegen's generated registration: the authoritative op -> Wrapper<Name>
# map. Read directly rather than through codegen_mudnn.wrapper_map(), which drags
# in codegen_ops -> torchgen (a module-level sys.exit without it) and would make
# this generator's --check unrunnable in the lean codegen-checks CI job that its
# siblings run in.
REGISTER_INC = REPO / "csrc/aten/generated/register.inc"


def wrapper_map():
    """op name -> Wrapper<Name>, read back from the CUDA codegen's register.inc."""
    if not REGISTER_INC.exists():
        return {}
    text = REGISTER_INC.read_text()
    return dict(re.findall(r'^\s*m\.impl\("([^"]+)",\s*(\w+)\);', text, flags=re.M))


INC_HEADER = """\
// Copyright (c) 2026, BAAI. All rights reserved.
//
// @generated by scripts/codegen/codegen_iluvatar_flaggems.py -- DO NOT EDIT.
//
// m.impl() lines for the FlagGems Python ops Iluvatar routes to the `flaggems`
// backend. Included by register.cc inside TORCH_LIBRARY_IMPL(aten, PrivateUse1)
// when USE_ILUVATAR and FLAGOS_FLAGGEMS_PYTHON are set. Iluvatar also has a
// vendor-native iluvatar_register.inc (from codegen_iluvatar.py), so this is one
// half of the platform's PrivateUse1 surface, disjoint from the native half and
// generated to stay that way: an op routed to `flaggems` that is not claimed
// here reaches the dispatcher with an empty kFlagGems slot and raises "backend
// not registered" instead of falling back to cpu_fallback.
//
// Excluded ops come from NATIVE_TRITON_GAPS['iluvatar'] in
// scripts/codegen/gen_vendor_confs.py: the 37 defect ops a BI-V150 overload
// survey measured failing (tests/manual/flaggems_overload_survey.py), now routed
// off the FlagGems path to the native slot or to cpu_fallback. The list below is
// the shared FlagGems ceiling (640) minus those 37, so 603.
//
// Measured twice against this same conf, 2026-10-14 over the 639-op cohort
// (STRICT 379 / BASIC_ONLY 66 / FAILED 58 / UNTESTED 136) and 2026-10-15 over the
// narrower 603-op cohort (STRICT 380 / BASIC_ONLY 66 / FAILED 21 / UNTESTED 136).
// The FAILED drop is the cohort change, not a fix: the 37 gap ops carried most of
// the old FAILED count, and no op newly failed between the runs. The remaining 21
// are survey synthesis limits and stay here.
//
// 2026-10-20: `mean`, `mean.dim`, `mm` and `mm.out` joined the gap set from the
// CI lane's own measurements rather than a survey run (issue #570) -- the
// keepdim mean returns wrong values, and the mm tuning perf model rejects
// float64 -- so the list is now 41 and this file registers 599. Two more
// joined later the same day from the lane's "vendor backend, main ops" group
// (`slice_backward`, whose FlagGems kernel assumes a contiguous grad_output,
// and `where.self_out`, the out= contract): 43 gapped, 597 registered.
//
// `mm` left the gap-exclusion path and moved to the native `.inc` on this same
// date, for the duplicate-registration reason below: it is gapped *and* the
// native `.inc` now claims it. Its `flaggems` conf route went to `none` in the
// same step, so nothing dispatches to a FlagGems `mm` slot that is not here.
//
// 2026-10-21: `add.Tensor`, `add.Scalar`, `add_.Tensor`, `add_.Scalar` and
// `div_.Tensor` joined the gap set for issue #570 -- FlagGems' complex `add`
// returns zeros for complex128 and its complex `div` raises for complex64 --
// and the three in-place spellings are answered by `csrc/aten/register.cc`.
// The gap set is now 59. This file registers 585, which is the 640-op FlagGems
// ceiling minus the 59 gaps minus the 11 native slots plus the 8 ops that are
// both gapped and natively claimed (the exclusion is a union, not a sum). The
// "603" above is the opening paragraph's snapshot at the first survey and is
// kept for provenance; the registrations are this file's `m.impl` lines.
//
// Re-measure and move entries in or out of that set only from BI-V150 results,
// never by assumption -- and note the DCU precedent: most of the 37 are the
// device-name mismatch that _ALIGNED_VENDORS
// (torch_fl/accelerator/cuda/_cuda_compat.py) remediates, so an A/B survey after
// adding iluvatar there is the way most of them come back.
"""


def target_ops() -> list:
    """Sorted op list to register, with the exclusion reasons attached."""
    wrappers = wrapper_map()
    if not wrappers:
        raise SystemExit(
            f"{REGISTER_INC.relative_to(REPO)} is missing or empty; run "
            "scripts/codegen/codegen_ops.py first -- the wrapper symbols are read from it."
        )

    # Iluvatar's VENDORS slot names its native .inc, so vendor_native_ops()
    # returns the ops codegen_iluvatar.py gives an m.impl of their own -- the
    # ones subtracted below, because a second m.impl for one op is a duplicate
    # registration. Read it from the table rather than naming a path here, so
    # the two cannot disagree.
    native = g.vendor_native_ops(VENDOR)
    gaps = g.NATIVE_TRITON_GAPS.get(VENDOR, set())
    pending = (
        g.FLAGGEMS_PENDING_NATIVE_OPS
        if VENDOR in g.FLAGGEMS_PENDING_NATIVE_VENDORS
        else frozenset()
    )

    # This platform's ceiling, not the shared one: only cuda reads the widened
    # set, so anything else here asks for wrappers register.inc does not have.
    flaggems_py = g.flaggems_python_ops_for("iluvatar")
    wanted = (set(flaggems_py) - gaps) - native - pending
    unknown = sorted(wanted - set(wrappers))
    if unknown:
        raise SystemExit(
            "no generated wrapper for: "
            + ", ".join(unknown)
            + f"\n{REGISTER_INC.relative_to(REPO)} has no m.impl() line for these ops."
        )

    return (
        sorted(wanted),
        sorted((native & set(flaggems_py)) - pending),
        sorted(gaps),
    )


def render() -> str:
    ops, via_native, gaps = target_ops()
    lines = [INC_HEADER]
    lines.append("// Excluded ops, left to cpu_fallback:\n")
    for op in gaps:
        lines.append(f"//   - {op}\n")
    lines.append("//\n")
    lines.append(
        f"// Total: {len(ops)} ops registered here, {len(via_native)} further "
        f"FlagGems ops already claimed by {VENDOR}_register.inc.\n\n"
    )
    wrappers = wrapper_map()
    lines.extend(f'  m.impl("{op}", {wrappers[op]});\n' for op in ops)
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed .inc is stale instead of rewriting it",
    )
    args = ap.parse_args()

    text = render()
    rel = OUT_INC.relative_to(REPO)

    if args.check:
        current = OUT_INC.read_text() if OUT_INC.exists() else ""
        if current != text:
            raise SystemExit(f"{rel} is stale; run: python3 {Path(__file__).name}")
        print(f"[check] {rel} is up to date")
        return

    OUT_INC.parent.mkdir(parents=True, exist_ok=True)
    OUT_INC.write_text(text)
    ops, via_native, gaps = target_ops()
    print(f"[gen] {rel}  ({len(ops)} m.impl lines, {len(gaps)} gaps excluded)")
    print(
        f"      {len(via_native)} FlagGems ops already registered by {VENDOR}_register.inc"
    )


if __name__ == "__main__":
    main()
