# Generate the Cambricon MLU (CNNL) operator layer.
#
# This backend is FlagGems-primary: `backends_cambricon.conf` routes the shared
# FlagGems ceiling to the Python path and everything else to `none`. A vendor
# kernel exists here only where FlagGems cannot serve the op or serves it too
# slowly to matter, and the ops below are that short list -- not a coverage goal.
#
# Each op is here after a measurement:
#
#   * `mul` (both spellings) and `embedding_dense_backward`: FlagGems' cambricon
#     `mul` compares the tensor's device name against the vendor's expected
#     "mlu", while torch_fl registers PrivateUse1 as "flagos", so the guard
#     rejects every call and the op redispatches or falls back to the host
#     (flagos-ai/FlagGems#8448). A Qwen3 training step measured 188 `mul.out`
#     fallbacks, the largest single source of host round trips in the model.
#   * `add`, `neg`, `clone`, `sum.dim`, `mm`, `bmm`: FlagGems serves these, but
#     through its Python/Triton path, where one launch costs a few hundred
#     microseconds of interpreter time whatever the tensor's size holds. A
#     Qwen3 training step measured 183 `mul` dispatches at 548 us each against
#     22 us for the same multiply on the native path, and the whole step's CPU
#     submission time equalled its wall time -- the device was waiting on the
#     host. These are the hot ones that measurably move that ratio.
#
# Every kernel body is emitted from here rather than written by hand, which is
# the AGENTS.md rule for non-CUDA platforms. The register file this script
# writes is also what `gen_vendor_confs.py` reads to decide routing, so the conf
# and the registrations cannot disagree about what this backend claims.
#
# Run it to (re)generate csrc/aten/backends/cambricon/generated/; `--check`
# verifies the committed artifacts are current without writing, which is the
# mode CI uses.

