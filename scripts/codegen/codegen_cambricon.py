# Generate the Cambricon MLU (CNNL) operator layer.
#
# This backend is FlagGems-primary: `backends_cambricon.conf` routes the shared
# FlagGems ceiling to the Python path and everything else to `none`. A vendor
# kernel exists here only where FlagGems cannot serve the op, and the register
# file this script emits is that short list -- not a coverage goal.
#
# The first entry is `mul.Tensor`, and the reason is a specific defect rather
# than a preference: FlagGems' cambricon `mul` compares the tensor's device name
# against the vendor's expected name ("mlu"), torch_fl registers PrivateUse1 as
# "flagos", and the mismatch makes the op redispatche into itself forever
# (flagos-ai/FlagGems#8448). With that op unreachable and no vendor kernel, every
# `mul` took `cpu_fallback` -- 330 of 333 fallbacks on one Qwen3 training step.
#
# Ops are added here one at a time, each after a measurement that says FlagGems
# cannot carry it. `NATIVE_OPS` below IS the coverage set, and
# `gen_vendor_confs.py` reads the emitted register file to build the conf, so the
# two cannot disagree about what this backend claims.
#
# Run it to (re)generate csrc/aten/backends/cambricon/generated/; `--check`
# verifies the committed artifact is current without writing, which is the mode
# CI uses.

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "csrc/aten/backends/cambricon/generated"

HEADER = """\
// Copyright (c) 2026, BAAI. All rights reserved.
//
// @generated by scripts/codegen/codegen_cambricon.py -- DO NOT EDIT.
//
// The ops this backend serves natively through CNNL. Everything in the shared
// FlagGems ceiling that is not listed here is routed to the Python path by
// backends_cambricon.conf; anything in neither stays `none` and reaches
// cpu_fallback. An op belongs here only when FlagGems cannot serve it, which is
// why this list is short and why each entry has a measurement behind it.
//
// Included from the USE_CAMBRICON arm of csrc/aten/register.cc when
// FLAGOS_CAMBRICON_KERNEL is defined.
"""

# The ops this backend claims on PrivateUse1, and the C++ function that answers
# each. Ordered by op name so a regeneration cannot reorder the file.
NATIVE_OPS = {
    "mul.Tensor": "MulTensor",
}


def render() -> str:
    lines = [HEADER]
    for op in sorted(NATIVE_OPS):
        fn = NATIVE_OPS[op]
        lines.append(f'  m.impl("{op}", at::native::flagos::cambricon::{fn});')
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed artifact is current; write nothing",
    )
    args = ap.parse_args()

    target = OUT_DIR / "cambricon_register.inc"
    text = render()

    if args.check:
        if not target.is_file():
            print(f"error: {target} is missing", file=sys.stderr)
            return 1
        if target.read_text() != text:
            print(f"error: {target} is stale", file=sys.stderr)
            print(f"run: python3 {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"[check] {target.relative_to(REPO_ROOT)} is up to date")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(f"[gen] {target.relative_to(REPO_ROOT)}  ({len(NATIVE_OPS)} m.impl lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
