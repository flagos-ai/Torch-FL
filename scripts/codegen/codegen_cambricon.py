# cnnlSoftmaxForward reduces over "the low dimension", which is aten's dim=-1 and
# the only axis this backend sees a softmax over. _safe_softmax is what SDPA's
# backward calls; left on FlagGems it measured 2809 us against 1703 us for
# torch.softmax on the same 8.4M-element tensor, and against 169 us for one
# elementwise pass over it.
T_SOFTMAX = """\
at::Tensor {kernel}(const at::Tensor& self, int64_t dim, std::optional<at::ScalarType> dtype) {{
  const at::ScalarType input_dtype = self.scalar_type();
  TORCH_CHECK(
      SupportedFloatDtype(input_dtype),
      "flagos cambricon: {op} does not serve ", input_dtype);
  TORCH_CHECK(
      self.device().type() == c10::DeviceType::PrivateUse1,
      "flagos cambricon: {op} requires a device tensor");
  TORCH_CHECK(
      self.dim() > 0,
      "flagos cambricon: {op} does not serve a zero-rank tensor");
  const int64_t resolved = dim < 0 ? dim + self.dim() : dim;
  TORCH_CHECK(
      resolved == self.dim() - 1,
      "flagos cambricon: {op} serves the last axis only, got ", dim);
  TORCH_CHECK(
      !dtype.has_value() || *dtype == at::kFloat || *dtype == input_dtype,
      "flagos cambricon: {op} does not serve the requested dtype");

  CambriconDeviceGuard guard(self);
  const auto handle = HandleForDevice(static_cast<int>(self.device().index()));
  const auto wide = Widen(self, handle);
  const bool strided = wide.data_ptr() == self.data_ptr();
  auto output = at::empty(self.sizes(), self.options().dtype(at::kFloat));
  // cnnlSoftmaxForward's LOW_DIMENSION mode reduces the last axis of a
  // three-dimensional descriptor, and rejects anything else: a 4-D
  // (2,16,512,512) descriptor came back "Input and output shapes must be
  // identical and three-dimensional". Folding every leading axis into one keeps
  // the reduced axis in the same place, so the answer is unchanged -- a softmax
  // over the last axis does not care how the rows before it are grouped.
  //
  // The collapsed view is taken with as_strided, not reshape: reshape would copy
  // a non-contiguous operand to make the collapse legal, which is the very copy
  // this kernel avoids.
  // Exactly three dimensions: a probe against this SDK showed rank 2 and rank 4
  // both rejected with "Input and output shapes must be identical and
  // three-dimensional", and rank 3 accepted. So every axis before the last two
  // is folded into one, which moves nothing -- a softmax over the last axis does
  // not care how the rows before it are grouped.
  const int64_t rank = self.dim();
  std::vector<int64_t> folded;
  std::vector<int64_t> folded_strides;
  if (rank <= 3) {{
    folded.assign(self.sizes().begin(), self.sizes().end());
    folded_strides.assign(wide.strides().begin(), wide.strides().end());
    while (folded.size() < 3) {{
      folded.insert(folded.begin(), 1);
      folded_strides.insert(folded_strides.begin(), 0);
    }}
  }} else {{
    int64_t leading = 1;
    for (int64_t axis = 0; axis + 2 < rank; ++axis) {{
      leading *= self.size(axis);
    }}
    folded = {{leading, self.size(rank - 2), self.size(rank - 1)}};
    // Folding axes 0..rank-3 leaves the step between consecutive blocks, which
    // is the stride of the last axis being merged.
    folded_strides = {{wide.stride(rank - 3), wide.stride(rank - 2),
                       wide.stride(rank - 1)}};
  }}
  const auto wide_3d = wide.as_strided(folded, folded_strides);
  auto output_3d = output.as_strided(folded, folded_strides);

  TensorDesc in_desc, out_desc;
  if (strided) {{
    in_desc.SetStrided(wide_3d);
  }} else {{
    in_desc.Set(wide_3d);
  }}
  out_desc.Set(output_3d);

  size_t workspace_size = 0;
  CheckCnnl(
      cnnlGetSoftmaxForwardWorkspaceSize(
          handle, in_desc.get(), out_desc.get(), CNNL_SOFTMAX_ACCURATE,
          CNNL_SOFTMAX_MODE_LOW_DIMENSION, &workspace_size),
      "cnnlGetSoftmaxForwardWorkspaceSize");
  at::Tensor workspace;
  if (workspace_size > 0) {{
    workspace = at::empty(
        {{static_cast<int64_t>(workspace_size)}},
        self.options().dtype(at::kByte));
  }}
  const float one = 1.0f;
  const float zero = 0.0f;
  CheckCnnl(
      cnnlSoftmaxForward_v2(
          handle, CNNL_SOFTMAX_ACCURATE, CNNL_SOFTMAX_MODE_LOW_DIMENSION,
          &one, in_desc.get(), wide.const_data_ptr(), &zero, out_desc.get(),
          workspace_size,
          workspace_size > 0 ? workspace.mutable_data_ptr() : nullptr,
          output.data_ptr()),
      "cnnlSoftmaxForward_v2 ({op})");

  // What comes back is the requested dtype when there is one, otherwise the
  // input's: _safe_softmax on a half tensor answers in half, so returning the
  // float32 the kernel computes in would be a different op. Narrowing is one
  // pass, and the widening cast of the input was the other.
  const auto result_dtype = dtype.has_value() ? *dtype : input_dtype;
  if (output.scalar_type() == result_dtype) {{
    return output;
  }}
  auto result = at::empty(self.sizes(), self.options().dtype(result_dtype));
  Narrow(output, result, handle);
  return result;
}}

REGISTER_IMPL_TO_DISPATCHER({fn}, {disp}, Backend::kCambricon, {kernel});
"""
# _log_softmax is the same kernel with CNNL's log algorithm. Derived rather than
# copied: the two differ in exactly three places, and a copy silently drifts the
# moment either changes -- which is how a stale check on a `dtype` parameter this
# signature does not have reached the compiler.
T_LOG_SOFTMAX = (
    T_SOFTMAX.replace(
        "at::Tensor {kernel}(const at::Tensor& self, int64_t dim, "
        "std::optional<at::ScalarType> dtype) {{",
        "at::Tensor {kernel}(const at::Tensor& self, int64_t dim, "
        "bool half_to_float) {{",
    )
    .replace("CNNL_SOFTMAX_ACCURATE", "CNNL_SOFTMAX_LOG")
    .replace(
        "  TORCH_CHECK(\n"
        "      !dtype.has_value() || *dtype == at::kFloat || *dtype == input_dtype,\n"
        '      "flagos cambricon: {op} does not serve the requested dtype");',
        "  // half_to_float asks for a float32 answer from a half input;\n"
        "  // there is no dtype argument to validate here.\n"
        "  TORCH_CHECK(\n"
        "      !half_to_float || input_dtype == at::kHalf ||\n"
        "          input_dtype == at::kBFloat16,\n"
        '      "flagos cambricon: {op} serves half_to_float on a half tensor only");',
    )
    .replace(
        "  const auto result_dtype = dtype.has_value() ? *dtype : input_dtype;",
        "  const auto result_dtype = half_to_float ? at::kFloat : input_dtype;",
    )
)

# The derivation must have changed all three, or the template did not match.
assert "CNNL_SOFTMAX_LOG" in T_LOG_SOFTMAX
assert "half_to_float ? at::kFloat" in T_LOG_SOFTMAX
# Comment lines are stripped first: the replacement above introduces a comment
# that mentions the word.
_CODE_ONLY = "\n".join(
    ln
    for ln in T_LOG_SOFTMAX.split("CambriconDeviceGuard")[0].split("\n")
    if not ln.lstrip().startswith("//")
)
for _stale in ("dtype.has_value()", "*dtype ==", "!dtype"):
    assert _stale not in _CODE_ONLY, (
        "T_LOG_SOFTMAX still reads a `dtype` parameter it does not have: " + _stale
    )

T_CLONE = """\
namespace {{

::std::optional<at::Tensor> {kernel}(
    const at::Tensor& self, ::std::optional<at::MemoryFormat> memory_format) {{
  if (self.device().type() != c10::DeviceType::PrivateUse1) {{
    return ::std::nullopt;
  }}
  // FLAGOS_OP_clone=<backend> is the conf's per-op override, and clone has no
  // dispatcher slot for it to act on, so the hook reads it itself. Anything but
  // "cambricon" declines, which is how a build can be taken back to the ATen
  // route without being recompiled.
  {{
    const char* want = std::getenv("FLAGOS_OP_clone");
    if (want != nullptr && std::strcmp(want, "cambricon") != 0) {{
      return ::std::nullopt;
    }}
  }}
  if (!SupportedFloatDtype(self.scalar_type())) {{
    return ::std::nullopt;
  }}
  if (memory_format.has_value() &&
      *memory_format != at::MemoryFormat::Contiguous) {{
    return ::std::nullopt;
  }}
  // An empty tensor has nothing to gather, and describing it as a strided copy
  // is a call for a result that is already correct.
  if (self.numel() == 0) {{
    return at::empty(self.sizes(), self.options());
  }}

  CambriconDeviceGuard guard(self);
  const auto handle = HandleForDevice(static_cast<int>(self.device().index()));
  auto result = at::empty(self.sizes(), self.options());
  TensorDesc in_desc, out_desc;
  // The source keeps its own strides: that is the whole point, and it is what
  // cnnlSetTensorDescriptorEx is for. It requires the innermost stride to be 1,
  // which is what a view of a dense tensor has.
  in_desc.SetStrided(self);
  out_desc.Set(result);
  CheckCnnl(
      cnnlCopy_v2(
          handle, in_desc.get(), self.const_data_ptr(), out_desc.get(),
          result.mutable_data_ptr(), nullptr, 0),
      "cnnlCopy_v2 (clone)");
  return result;
}}

}} // namespace (anon)
"""

T_CLONE_HOOK = """
// Installs this backend's clone kernel into register.cc's vendor table. Emitted
// after the at::native::flagos::cambricon namespace closes, because it has to
// name both the kernel and a variable that lives outside it.
//
// register.cc owns this table -- weak there, so a build with no backend that
// fills it still links -- and consults it for a PrivateUse1 tensor. This file
// only installs into it; the variable is not defined here, because two
// definitions of one global in different objects is an ODR violation even when
// one of them is weak.
extern CloneVendorFn g_clone_vendor;

namespace {{

// Runs before main and before any tensor can be cloned, because it is a static
// initialiser in the same translation unit as the kernels.
__attribute__((constructor)) void InstallCloneHook() {{
  g_clone_vendor = static_cast<CloneVendorFn>(
      at::native::flagos::cambricon::{kernel});
}}

}} // namespace


"""


CATEGORIES = {
    "reduce_all": T_REDUCE_ALL,
    "ones_like": T_ONES_LIKE,
    "unary_op": T_UNARY_OP,
    "scalar": T_SCALAR,
    "mean_dim": T_MEAN_DIM,
    "matmul": T_MATMUL,
    "bmm": T_BMM,
    "sum_dim": T_SUM_DIM,
    "embedding_backward": T_EMBEDDING_BACKWARD,
    "softmax": T_SOFTMAX,
    "clone": T_CLONE,
}


def wrapper_map():
    """op name -> wrapper function, read from the generated register file."""

    text = REGISTER_INC.read_text()
    return dict(re.findall(r'm\.impl\(\s*"([^"]+)"\s*,\s*(\w+)\)', text))


def render():
    """(kernels.cc text, register.inc text, [(op, category)]).

    Raises on an op that has no wrapper in the CUDA-side register file, so a
    missing `codegen_ops.py` run fails loudly here instead of emitting a file
    that will not link.
    """
    wrappers = wrapper_map()
    bodies = []
    covered = []
    # clone is served through CloneVendorHook, not through a PrivateUse1 m.impl:
    # register.cc installs WrapperClone for every platform and the hook lives
    # inside it. Claiming the op here as well would add a second registration
    # that dispatches to a slot the wrapper never consults.
    hook_only = {"clone"}
    for op, category in sorted(OPS.items()):
        if op in hook_only:
            fn, disp = schema_to_cpp_name(op)
            kernel = fn[:-2] + "KernelCambricon"
            fields = {"kernel": kernel, "fn": fn, "disp": disp, "op": op}
            bodies.append(CATEGORIES[category].format(**fields))
            continue
        wrapper = wrappers.get(op)
        if wrapper is None:
            raise SystemExit(
                f"error: {op} has no wrapper in "
                f"{REGISTER_INC.relative_to(REPO_ROOT)}; run "
                "scripts/codegen/codegen_ops.py first"
            )
        fn, disp = schema_to_cpp_name(op)
        kernel = fn[:-2] + "KernelCambricon"
        if category == "binary":
            cnnl_op, _ = BINARY_OPS[op]
            body = T_BINARY.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                cnnl_op=cnnl_op,
                signature_extra=BINARY_SIGNATURE_EXTRA.get(op, ""),
                prologue_extra=BINARY_PROLOGUE_EXTRA.get(op, ""),
            )
        elif category == "softmax_backward":
            body = T_SOFTMAX_BACKWARD.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "slice_backward":
            body = T_SLICE_BACKWARD.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "silu":
            body = T_SILU.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "silu_backward":
            body = T_SILU_BACKWARD.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "where":
            body = T_WHERE.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "unary_op":
            body = T_UNARY_OP.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                entry=UNARY_ENTRY[op],
            )
        elif category == "zero_inplace":
            body = T_ZERO_INPLACE.format(
                kernel=kernel, fn=fn, disp=disp, op=op
            )
        elif category == "fill":
            body = T_FILL.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "log_softmax":
            body = T_LOG_SOFTMAX.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "embedding":
            body = T_EMBEDDING.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "cumsum":
            body = T_CUMSUM.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "div_out":
            body = T_DIV_OUT.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "div_scalar":
            body = T_DIV_SCALAR.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "lerp_scalar":
            body = T_LERP_SCALAR.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "addcdiv_fused":
            body = T_ADDCDIV_FUSED.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "addcmul_fused":
            body = T_ADDCMUL_FUSED.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "addcmul":
            body = T_ADDCMUL.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "inplace_binary":
            body = T_INPLACE_BINARY.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                aten=INPLACE_BINARY_ATEN[op],
                cnnl_op=INPLACE_BINARY_CNNL[op],
            )
        elif category == "inplace_scalar":
            aten, sig, host_body, scale_b = INPLACE_SCALAR_ATEN[op]
            body = T_INPLACE_SCALAR.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                aten=aten,
                signature_extra=sig,
                host_body=host_body,
                scale_b=scale_b,
                cnnl_op=INPLACE_SCALAR_CNNL[op],
            )
        elif category == "sqrt":
            body = T_SQRT.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "metadata":
            params, body = METADATA_OPS[op]
            # Deliberately not .format()ed: these bodies are plain C++ and their
            # braces are code, not fields. Formatting them raised
            # KeyError('\\n    perm') on the transpose body's for-loop brace.
            body = "\n".join(("  " + ln) if ln else ln for ln in body.split("\n"))
            body = T_METADATA.format(
                kernel=kernel, fn=fn, disp=disp, op=op, params=params, body=body
            )
        elif category == "new_ones":
            body = T_NEW_ONES.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "pow":
            body = T_POW.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "cat":
            body = T_CAT.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "host_built":
            params, build = HOST_BUILT_OPS[op]
            body = T_HOST_BUILT.format(
                kernel=kernel, fn=fn, disp=disp, op=op, params=params, host_build=build
            )
        elif category in ("zeros", "zeros_like"):
            body = (T_ZEROS if category == "zeros" else T_ZEROS_LIKE).format(
                kernel=kernel, fn=fn, disp=disp, op=op
            )
        elif category == "ones":
            body = T_ONES.format(kernel=kernel, fn=fn, disp=disp, op=op)
        elif category == "reduce_all":
            body = T_REDUCE_ALL.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                reduce_kind=REDUCE_ALL_OP[op],
            )
        elif category == "scalar":
            cnnl_op, _, extra = SCALAR_OPS[op]
            body = T_SCALAR.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                cnnl_op=cnnl_op,
                extra=extra,
            )
        elif category == "binary_out":
            base_op = OUT_FORWARDS_TO[op]
            base_fn, _ = schema_to_cpp_name(base_op)
            body = T_BINARY_OUT.format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                op=op,
                base=base_fn[:-2] + "KernelCambricon",
                cnnl_op=BINARY_OUT_CNNL[op],
            )
        else:
            # sum.dim / mean.dim differ only in the reduce kind, which is the
            # one thing their shared template takes beyond the op name.
            fields = {"kernel": kernel, "fn": fn, "disp": disp, "op": op}
            if op in REDUCE_DIM_OP:
                fields["reduce_kind"] = REDUCE_DIM_OP[op]
            body = CATEGORIES[category].format(**fields)
        bodies.append(body)
        covered.append((op, category))
    return (
        FILE_HEADER
        + "\n".join(bodies)
        + FILE_FOOTER
        # The clone hook has to sit outside the namespace, so it is appended to
        # the footer rather than to a body.
        + (
            T_CLONE_HOOK.format(
                kernel=schema_to_cpp_name("clone")[0][:-2] + "KernelCambricon"
            )
            if "clone" in OPS
            else ""
        )
        + FILE_TAIL,
        INC_HEADER
        + "".join(f'  m.impl("{op}", {wrappers[op]});\n' for op, _ in sorted(covered)),
        covered,
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed artifacts are current; write nothing",
    )
    args = ap.parse_args()

    cc_text, inc_text, covered = render()

    if args.check:
        stale = [
            target
            for target, text in ((OUT_CC, cc_text), (OUT_INC, inc_text))
            if (target.read_text() if target.exists() else "") != text
        ]
        if stale:
            for target in stale:
                print(
                    f"[check] stale: {target.relative_to(REPO_ROOT)}", file=sys.stderr
                )
            print("error: run scripts/codegen/codegen_cambricon.py", file=sys.stderr)
            return 1
        print(f"[check] {len(covered)} kernel(s) up to date")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_CC.write_text(cc_text)
    OUT_INC.write_text(inc_text)
    print(f"[gen] {OUT_CC.relative_to(REPO_ROOT)}  ({len(covered)} ops)")
    print(f"[gen] {OUT_INC.relative_to(REPO_ROOT)}  ({len(covered)} m.impl lines)")
    for op, category in covered:
        print(f"       + {op} [{category}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
