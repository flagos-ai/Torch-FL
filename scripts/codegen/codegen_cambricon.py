T_REDUCE_ALL = """\
at::Tensor {kernel}(
    const at::Tensor& self, std::optional<at::ScalarType> dtype_opt) {{
  const at::ScalarType dtype = self.scalar_type();
  TORCH_CHECK(
      SupportedFloatDtype(dtype),
      "flagos cambricon: {op} does not serve ", dtype);
  TORCH_CHECK(
      !dtype_opt.has_value() || SupportedFloatDtype(*dtype_opt),
      "flagos cambricon: {op} does not serve the requested dtype");
  TORCH_CHECK(
      self.device().type() == c10::DeviceType::PrivateUse1,
      "flagos cambricon: {op} requires a device tensor");
  TORCH_CHECK(self.numel() > 0, "flagos cambricon: {op} of an empty tensor");

  CambriconDeviceGuard guard(self);
  const auto handle = HandleForDevice(static_cast<int>(self.device().index()));
  const bool widen = ComputesInFloat32(dtype);
  const auto input = self.contiguous();
  const auto wide_input = widen ? Widen(input, handle) : input;
  const auto compute = widen ? at::kFloat : dtype;

  // Reducing every axis leaves one element, so both sides are described at
  // their flattened rank rather than carrying the operand's shape through.
  std::vector<int64_t> flat_input_shape{{input.numel()}};
  auto flat_input = wide_input.reshape(flat_input_shape);
  auto flat_out = at::empty({{1}}, self.options().dtype(compute));
  std::vector<int> axes{{0}};

  cnnlReduceDescriptor_t desc = nullptr;
  CheckCnnl(cnnlCreateReduceDescriptor(&desc), "cnnlCreateReduceDescriptor");
  CheckCnnl(
      cnnlSetReduceDescriptor_v3(
          desc, axes.data(), 1, {reduce_kind}, ToCnnlDtype(compute),
          CNNL_NOT_PROPAGATE_NAN, CNNL_REDUCE_NO_INDICES, CNNL_32BIT_INDICES,
          /*p=*/0.0f, /*acc_sqrt=*/false),
      "cnnlSetReduceDescriptor_v3 ({op})");
  TensorDesc in_desc, out_desc;
  in_desc.Set(flat_input);
  out_desc.Set(flat_out);

  size_t workspace_size = 0;
  CheckCnnl(
      cnnlGetReduceOpWorkspaceSize_v2(
          handle, in_desc.get(), out_desc.get(), /*indices_desc=*/nullptr, desc,
          &workspace_size),
      "cnnlGetReduceOpWorkspaceSize_v2 ({op})");
  at::Tensor workspace;
  if (workspace_size > 0) {{
    workspace = at::empty(
        {{static_cast<int64_t>(workspace_size)}},
        self.options().dtype(at::kByte));
  }}
  CheckCnnl(
      cnnlReduce_v2(
          handle, desc, in_desc.get(), flat_input.const_data_ptr(),
          /*alpha=*/nullptr, /*beta=*/nullptr,
          workspace_size > 0 ? workspace.mutable_data_ptr() : nullptr,
          workspace_size, out_desc.get(), flat_out.mutable_data_ptr(),
          /*indices_desc=*/nullptr, /*indices=*/nullptr),
      "cnnlReduce_v2 ({op})");
  cnnlDestroyReduceDescriptor(desc);

  auto result = at::empty(
      {{}}, self.options().dtype(compute));
  if (compute == at::kFloat) {{
    result.copy_(flat_out.reshape({{}}));
  }} else {{
    Narrow(flat_out, result, handle);
  }}
  return result;
}}

REGISTER_IMPL_TO_DISPATCHER({fn}, {disp}, Backend::kCambricon, {kernel});
"""

