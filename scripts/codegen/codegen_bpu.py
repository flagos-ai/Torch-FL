# Generate the D-Robotics BPU operator layer.
#
# The BPU has no per-operator entry point -- hbDNNInferV2 takes a compiled
# .hbm -- so this backend stays small on purpose: an op is claimed on
# PrivateUse1 only once it has an artifact family in the operator library, and
# the conf only names this backend for the ops the emitted register file
# claims. The op set below IS the coverage set, and it matches the tables in
# scripts/vendor/build_bpu_oplib.py; a divergence between the two is caught by
# tests/unit/bpu/test_eager_dispatch.py, which pins the Python side.
#
# Each kernel is the same three steps: take the CPU round-trip when the dtype
# or width is outside what the library carries, otherwise copy into the
# bucket-sized device buffer and submit. The runtime that does the copy and the
# submit lives in csrc/aten/backends/bpu/bpu_oplib.cc.
#
# There is no conf writer here. torch_fl/configs/backends_drobotics.conf is
# generated by scripts/codegen/gen_vendor_confs.py from the emitted
# bpu_register.inc, so the register file is the single hand-off and the conf
# cannot advertise a route this file does not register.
#
# Run it to (re)generate csrc/aten/backends/bpu/generated/; `--check` verifies
# the committed artifacts are current without writing, which is the mode CI
# uses.

