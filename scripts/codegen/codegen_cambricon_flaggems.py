#!/usr/bin/env python3
"""Generate the Cambricon FlagGems registration list.

``csrc/aten/backends/cambricon/generated/cambricon_flaggems_register.inc``
claims the FlagGems Python ops on PrivateUse1 so that ``backends_cambricon.conf``
can route them to the ``flaggems`` backend. Without this file every
``flaggems`` route in the conf has no registered slot, and the call reaches the
dispatcher's empty ``kFlagGems`` slot and raises "backend not registered" instead
of falling back to CPU.

Cambricon has no vendor-native ``cambricon_register.inc`` yet (the CNNL kernels
are still being added), so unlike Iluvatar this file is the platform's *entire*
PrivateUse1 surface: the ops FlagGems does not cover are not registered at all,
which is what makes ``none`` in the conf a real ``cpu_fallback`` rather than a
raise. ``VENDORS["cambricon"]`` in ``gen_vendor_confs.py`` already names both
files, so ``vendor_native_ops()`` returns an empty set today and starts
subtracting the moment a native ``.inc`` lands -- the disjointness that matters
when both are included into one ``TORCH_LIBRARY_IMPL`` body.

The list is ``flaggems_python_ops_for("cambricon")`` minus
``NATIVE_TRITON_GAPS['cambricon']``,
minus ``FLAGGEMS_PENDING_NATIVE_OPS`` (for as long as ``cambricon`` is in
``FLAGGEMS_PENDING_NATIVE_VENDORS``; it is not). Each op is emitted with the
wrapper symbol read back from the CUDA codegen's ``generated/register.inc``
rather than derived from the op name, for the same reason as the Iluvatar
generator: ``add.Tensor`` is served by ``WrapperAddTensor`` while
``_adaptive_avg_pool2d`` is served by ``WrapperPrivAdaptiveAvgPool2d``.

**No Cambricon measurement backs an exclusion set.** ``NATIVE_TRITON_GAPS`` has
no ``cambricon`` entry, so this registers the full shared FlagGems ceiling (640).
That is "not yet measured", not "known to work": the MLU590 overload survey
(``tests/manual/flaggems_overload_survey.py``, the harness the other vendors
used) turns measured failures into ``NATIVE_TRITON_GAPS['cambricon']`` entries,
after which both this generator and ``gen_vendor_confs.py`` are rerun.

One Cambricon-specific precondition is worth stating here, because these routes
are dead without it: both the FlagGems backend and the Triton mlu driver
``import torch_mlu``, which this build deliberately does not install. The import
is satisfied by the shim in ``torch_fl/accelerator/cambricon/
_cambricon_compat.py``; it must have run before ``flag_gems`` is first imported.

Usage:
    python3 scripts/codegen/codegen_cambricon_flaggems.py            # rewrite the .inc
    python3 scripts/codegen/codegen_cambricon_flaggems.py --check    # exit 1 if stale
"""

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gen_vendor_confs as g  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
VENDOR = "cambricon"
OUT_INC = REPO / f"csrc/aten/backends/{VENDOR}/generated/{VENDOR}_flaggems_register.inc"
# The CUDA codegen's generated registration: the authoritative op -> Wrapper<Name>
# map. Read directly rather than through codegen_mudnn.wrapper_map(), which drags
# in codegen_ops -> torchgen (a module-level sys.exit without it) and would make
# this generator's --check unrunnable in the lean codegen-checks CI job that its
# siblings run in.
REGISTER_INC = REPO / "csrc/aten/generated/register.inc"


def wrapper_map():
    """op name -> Wrapper<Name>, read back from the CUDA codegen's register.inc."""
    if not REGISTER_INC.exists():
        return {}
    text = REGISTER_INC.read_text()
    return dict(re.findall(r'^\s*m\.impl\("([^"]+)",\s*(\w+)\);', text, flags=re.M))


INC_HEADER = """\
// Copyright (c) 2026, BAAI. All rights reserved.
//
// @generated by scripts/codegen/codegen_cambricon_flaggems.py -- DO NOT EDIT.
//
// m.impl() lines for the FlagGems Python ops Cambricon routes to the `flaggems`
// backend. Included by register.cc inside TORCH_LIBRARY_IMPL(aten, PrivateUse1)
// when USE_CAMBRICON and FLAGOS_FLAGGEMS_PYTHON are set.
//
// Cambricon has no vendor-native .inc yet, so this is the platform's entire
// PrivateUse1 surface: an op not listed here is not claimed at all, which is
// what lets a `none` route in backends_cambricon.conf reach cpu_fallback instead
// of raising "backend not registered". When a cnnl_register.inc lands,
// gen_vendor_confs.py's VENDORS row already makes this file subtract its ops,
// keeping the two disjoint as both are included into one TORCH_LIBRARY_IMPL body.
//
// The list is the shared FlagGems ceiling with no Cambricon subtraction: there
// is no measured MLU overload survey yet, so NATIVE_TRITON_GAPS has no
// 'cambricon' entry. This is "unmeasured", not "known good".
//
// Reminder that matters here more than elsewhere: the FlagGems cambricon backend
// and the Triton mlu driver both `import torch_mlu`, which this build
// deliberately does not install. The import is satisfied by the shim in
// torch_fl/accelerator/cambricon/_cambricon_compat.py; without it these routes
// cannot be reached at all.
"""


def target_ops() -> list:
    """Sorted op list to register, with the exclusion reasons attached."""
    wrappers = wrapper_map()
    if not wrappers:
        raise SystemExit(
            f"{REGISTER_INC.relative_to(REPO)} is missing or empty; run "
            "scripts/codegen/codegen_ops.py first -- the wrapper symbols are read from it."
        )

    # Empty today (cambricon's VENDORS row names no native .inc). Read from the
    # table rather than naming a path here, so the two cannot disagree once one
    # exists -- a second m.impl for one op is a duplicate registration.
    native = g.vendor_native_ops(VENDOR)
    gaps = g.NATIVE_TRITON_GAPS.get(VENDOR, set())
    pending = (
        g.FLAGGEMS_PENDING_NATIVE_OPS
        if VENDOR in g.FLAGGEMS_PENDING_NATIVE_VENDORS
        else frozenset()
    )

    # The same ceiling the conf is built from. The two files have to agree op
    # for op -- test_gen_vendor_confs.py::test_vendor_routing_never_exceeds_registration
    # requires the routed set to equal the registered one -- and this platform has
    # no native .inc to claim the difference. The unfrozen set is cuda's measured
    # ceiling; these routes have never been measured on an MLU, so they stay on
    # the frozen one until the survey runs, exactly as the conf's own ceiling
    # does (see flaggems_python_ops_for).
    ceiling = g.flaggems_python_ops_for(VENDOR)
    wanted = (set(ceiling) - gaps) - native - pending
    unknown = sorted(wanted - set(wrappers))
    if unknown:
        raise SystemExit(
            "no generated wrapper for: "
            + ", ".join(unknown)
            + f"\n{REGISTER_INC.relative_to(REPO)} has no m.impl() line for these ops."
        )

    return (
        sorted(wanted),
        sorted((native & g.flaggems_python_ops_for(VENDOR)) - pending),
        sorted(gaps),
    )


def render() -> str:
    ops, via_native, gaps = target_ops()
    lines = [INC_HEADER]
    lines.append("// Excluded ops, left to cpu_fallback:\n")
    for op in gaps:
        lines.append(f"//   - {op}\n")
    lines.append("//\n")
    lines.append(
        f"// Total: {len(ops)} ops registered here, {len(via_native)} further "
        f"FlagGems ops already claimed by {VENDOR}_register.inc.\n\n"
    )
    wrappers = wrapper_map()
    lines.extend(f'  m.impl("{op}", {wrappers[op]});\n' for op in ops)
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed .inc is stale instead of rewriting it",
    )
    args = ap.parse_args()

    text = render()
    rel = OUT_INC.relative_to(REPO)

    if args.check:
        current = OUT_INC.read_text() if OUT_INC.exists() else ""
        if current != text:
            raise SystemExit(f"{rel} is stale; run: python3 {Path(__file__).name}")
        print(f"[check] {rel} is up to date")
        return

    OUT_INC.parent.mkdir(parents=True, exist_ok=True)
    OUT_INC.write_text(text)
    ops, via_native, gaps = target_ops()
    print(f"[gen] {rel}  ({len(ops)} m.impl lines, {len(gaps)} gaps excluded)")
    print(
        f"      {len(via_native)} FlagGems ops already registered by {VENDOR}_register.inc"
    )


if __name__ == "__main__":
    main()
