DEVICE = """\
#include "musa_foreach.h"

#include <musa_bf16.h>
#include <musa_runtime.h>

namespace at::native::flagos::musa_foreach {
namespace {

// The vendor's scalar foreach path uses FP32 math and one fused multiply-add
// before rounding the result back to BF16.
template <Operation op>
__device__ float Apply(float x, float y, float z, float alpha) {
@FORMULAS@
}

template <Operation op>
__global__ void Pointwise(Batch batch) {
  unsigned first = 0;
  unsigned last = batch.count;
  while (last - first > 1) {
    const unsigned middle = (first + last) / 2;
    if (blockIdx.x < batch.operands[middle - 1].end_block) {
      last = middle;
    } else {
      first = middle;
    }
  }
  const auto& operand = batch.operands[first];
  const auto start_block = first ? batch.operands[first - 1].end_block : 0;
  const int64_t begin =
      static_cast<int64_t>(blockIdx.x - start_block) * kElementsPerBlock;
  const int64_t limit = begin + kElementsPerBlock;
  const int64_t end = limit < operand.elements ? limit : operand.elements;
  auto* result = static_cast<__mt_bfloat16*>(operand.result);
  const auto* a = static_cast<const __mt_bfloat16*>(operand.first);
  const auto* b = static_cast<const __mt_bfloat16*>(operand.second);
  for (int64_t i = begin + threadIdx.x; i < end; i += blockDim.x) {
    const float x = __bfloat162float(result[i]);
    const float y = __bfloat162float(a[i]);
    const float z = op == Operation::Lerp ? 0.0f : __bfloat162float(b[i]);
    result[i] = __float2bfloat16_rn(Apply<op>(x, y, z, operand.scalar));
  }
}

}  // namespace

musaError_t Launch(Operation operation, const Batch& batch, musaStream_t stream) {
  if (!batch.blocks) return musaSuccess;
  switch (operation) {
@LAUNCHES@
  }
  return musaGetLastError();
}

}  // namespace at::native::flagos::musa_foreach
"""

HOST = """\
#include "musa_foreach.h"
#include "../mudnn_common.h"
#include "../../../foreach_utils.h"

#include <ATen/ops/_foreach_addcdiv_native.h>
#include <ATen/ops/_foreach_addcmul_native.h>
#include <ATen/ops/_foreach_lerp_native.h>
#include <torch/library.h>

#include <algorithm>
#include <limits>

namespace at::native::flagos::musa_foreach {
namespace {

constexpr int64_t kMaxGrid = std::numeric_limits<int>::max();

bool Batchable(at::TensorList self, at::TensorList first, at::TensorList second) {
  return self.size() == first.size() && !self.empty() && self.front().defined() &&
      self.front().scalar_type() == at::kBFloat16 &&
      CanBatchForeach(self, first, second, kMaxGrid * kElementsPerBlock);
}

bool Run(Operation operation, at::TensorList self, at::TensorList first,
         at::TensorList second, const at::Scalar* scalar, at::ArrayRef<at::Scalar> scalars) {
  musa_ops::MusaDeviceGuard guard(self.front());
  const auto stream = reinterpret_cast<musaStream_t>(
      GetCurrentStreamForDevice(self.front().device().index()));
  Batch batch{};
  size_t start = 0;
  auto flush = [&](size_t end) {
    const auto status = Launch(operation, batch, stream);
    // Other MUSA targets use the existing ATen path when the wheel has no
    // matching image. A failed first launch leaves all tensors untouched.
    if (start == 0 && (status == musaErrorNoKernelImageForDevice ||
                       status == musaErrorInvalidDeviceFunction)) {
      return false;
    }
    TORCH_CHECK(status == musaSuccess, "MUSA foreach: ", musaGetErrorString(status));
    for (; start < end; ++start) self[start].unsafeGetTensorImpl()->bump_version();
    batch.count = 0;
    batch.blocks = 0;
    return true;
  };
  for (size_t i = 0; i < self.size(); ++i) {
    const int64_t elements = self[i].numel();
    if (!elements) continue;
    const int64_t blocks = (elements - 1) / kElementsPerBlock + 1;
    if ((batch.count == kTensorsPerBatch || batch.blocks + blocks > kMaxGrid) &&
        !flush(i)) return false;
    batch.blocks += static_cast<unsigned>(blocks);
    batch.operands[batch.count++] = {
        self[i].data_ptr(), first[i].const_data_ptr(),
        second.empty() ? nullptr : second[i].const_data_ptr(), elements,
        (scalar ? *scalar : scalars[i]).to<float>(), batch.blocks,
    };
  }
  return flush(self.size());
}

@HOST_ENTRIES@

}  // namespace
}  // namespace at::native::flagos::musa_foreach

TORCH_LIBRARY_IMPL(aten, PrivateUse1, m) {
@REGISTRATIONS@
}
"""

ENTRY = """\
void {name}(at::TensorList self, at::TensorList first{second_param}, {scalar_param}) {{
  if ({eligible}Batchable(self, first, {second}) &&
      Run(Operation::{name}, self, first, {second}, {scalar}, {scalars})) {{
    return;
  }}
  at::native::{fallback}(self, first{fallback_second}, value);
}}"""


def emit(directory):
    directory.mkdir(parents=True, exist_ok=True)
    formulas, launches, entries, registrations = [], [], [], []
    names = []
    for op, (name, fallback, ternary, scalar_list, formula) in OPERATORS.items():
        names.append(name)
        connector = "else " if formulas else ""
        formulas.append(
            f"  {connector}if constexpr (op == Operation::{name}) {{\n"
            + indent(formula, "    ")
            + "\n  }"
        )
        launches.append(
            f"    case Operation::{name}:\n"
            f"      Pointwise<Operation::{name}><<<batch.blocks, 256, 0, stream>>>(batch);\n"
            "      break;"
        )
        checks = []
        if ternary:
            checks.append("second.size() == self.size()")
        if scalar_list:
            checks.extend(
                (
                    "value.size() == self.size()",
                    "std::none_of(value.begin(), value.end(), [](const at::Scalar& s) { return s.isComplex(); })",
                )
            )
        else:
            checks.append("!value.isComplex()")
        entries.append(
            ENTRY.format(
                name=name,
                second_param=", at::TensorList second" if ternary else "",
                scalar_param=(
                    "at::ArrayRef<at::Scalar> value"
                    if scalar_list
                    else "const at::Scalar& value"
                ),
                eligible=" &&\n      ".join(checks) + " &&\n      ",
                second="second" if ternary else "{}",
                scalar="nullptr" if scalar_list else "&value",
                scalars="value" if scalar_list else "{}",
                fallback=fallback,
                fallback_second=", second" if ternary else "",
            )
        )
        registrations.append(
            f'  m.impl("{op}", TORCH_FN(at::native::flagos::musa_foreach::{name}));'
        )

    files = {
        "musa_foreach.h": HEADER.replace("@OPERATIONS@", ", ".join(names)),
        "musa_foreach.mu": DEVICE.replace("@FORMULAS@", "\n".join(formulas)).replace(
            "@LAUNCHES@", "\n".join(launches)
        ),
        "musa_foreach.cc": HOST.replace("@HOST_ENTRIES@", "\n\n".join(entries)).replace(
            "@REGISTRATIONS@", "\n".join(registrations)
        ),
    }
    for name, source in files.items():
        (directory / name).write_text(BANNER + source)
