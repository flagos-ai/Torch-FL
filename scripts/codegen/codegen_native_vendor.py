"""Generate typed vendor precision entries from policy and Torch schemas.

Only host metadata and library calls are emitted. Numerical implementations
come from the published vendor libraries. The policy names measured exceptions,
not model shapes or captured paths; all other routes remain unchanged.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import torchgen
from torchgen.api import structured
from torchgen.context import native_function_manager
from torchgen.gen import get_grouped_native_functions, parse_native_yaml
from torchgen.model import DispatchKey, NativeFunctionsGroup

sys.path.insert(0, str(Path(__file__).resolve().parent))
from codegen_ops import schema_to_cpp_name, unified_sig
from native_host_policy import precision_policy

ROOT = Path(__file__).resolve().parents[2]
ENTRY_PATH = ROOT / "csrc/aten/generated/native_vendor_entries.inc"
SOURCE_DIR = ROOT / "csrc/native_host/backends"
BANNER = "// Generated by scripts/codegen/codegen_native_vendor.py. Do not edit.\n"

HYGON_TO_DTYPE = """
namespace at::native {
void bfloat16_copy_kernel_cuda(at::TensorIteratorBase&);
void bfloat16tofloat32_copy_kernel_cuda(at::TensorIteratorBase&);
}  // namespace at::native

namespace at::native::flagos::vendor {
static at::Tensor ToDtype(const at::Tensor& input, at::ScalarType dtype,
                          bool non_blocking, bool copy,
                          std::optional<at::MemoryFormat> memory_format) {
  const auto source = input.scalar_type();
  const auto format = memory_format.value_or(at::MemoryFormat::Preserve);
  const bool supported_pair = (source == at::kBFloat16 && dtype == at::kFloat) ||
      (source == at::kFloat && dtype == at::kBFloat16);
  // The composite path supplies the copy's autograd node outside inference mode.
  if (!c10::InferenceMode::is_enabled() || !supported_pair || non_blocking || copy ||
      input.layout() != at::kStrided || input.numel() == 0 || !input.is_contiguous() ||
      input.is_neg() || input.is_conj() || input.has_names() ||
      (format != at::MemoryFormat::Preserve && format != at::MemoryFormat::Contiguous)) {
    return at::native::to(input, dtype, non_blocking, copy, memory_format);
  }

  RECORD_FUNCTION("flagos::hygon::to.dtype", std::vector<c10::IValue>());
  VendorScope scope(input);
  auto* allocator = at::GetAllocator(at::kPrivateUse1);
  constexpr c10::DispatchKeySet keys(c10::DispatchKey::PrivateUse1);
  auto output = format == at::MemoryFormat::Preserve
      ? at::detail::empty_strided_generic(input.sizes(), input.strides(), allocator, keys, dtype)
      : at::detail::empty_generic(input.sizes(), allocator, keys, dtype, at::MemoryFormat::Contiguous);
  auto iterator = at::TensorIteratorConfig()
      .add_output(output)
      .add_const_input(input)
      .check_all_same_dtype(false)
      .resize_outputs(false)
      .build();
  DescribeCudaMemory(iterator);
  if (dtype == at::kBFloat16) {
    at::native::bfloat16_copy_kernel_cuda(iterator);
  } else {
    at::native::bfloat16tofloat32_copy_kernel_cuda(iterator);
  }
  return output;
}
}  // namespace at::native::flagos::vendor

TORCH_LIBRARY_IMPL(aten, PrivateUse1, m) {
  m.impl("to.dtype", &at::native::flagos::vendor::ToDtype);
}
"""


def validate_policy(policy):
    if policy.get("schema_version") != 1 or policy.get("vendor") not in {
        "nvidia",
        "hygon",
        "thead",
    }:
        raise ValueError("unsupported vendor precision policy")
    seen = set()
    for row in policy["operators"]:
        if row["op"] in seen:
            raise ValueError(f"duplicate precision exception: {row['op']}")
        seen.add(row["op"])
        if not row.get("reason") or not row.get("dtypes"):
            raise ValueError("precision exceptions require evidence and dtypes")
        dtypes = {"Float", "BFloat16"}
        if row["family"] == "concatenate" and policy["vendor"] == "nvidia":
            dtypes.add("Long")
        if set(row["dtypes"]) - dtypes:
            raise ValueError("unmeasured precision dtype")
        if row["family"] not in {
            "structured",
            "softmax_backward_out",
            "reduction",
            "blas",
            "foreach",
            "concatenate",
            "binary_pointwise",
        }:
            raise ValueError("unsupported native vendor family")
        if policy["vendor"] == "thead" and (
            not row.get("guarded")
            or row["family"] not in {"binary_pointwise", "concatenate", "foreach"}
        ):
            raise ValueError("T-Head native vendor entries require a guarded route")
        if row["family"] == "softmax_backward_out" and (
            row["dtypes"] != ["Float"]
            or row["op"]
            not in {"_softmax_backward_data.out", "_log_softmax_backward_data.out"}
        ):
            raise ValueError("unsupported softmax gradient output contract")
        if row["family"] == "foreach" and (
            row["dtypes"] != ["BFloat16"] or not row["op"].startswith("_foreach_")
        ):
            raise ValueError("unmeasured native foreach contract")
        if row["family"] == "blas" and row.get("rank") not in (2, 3):
            raise ValueError("BLAS entries require matrix or batched-matrix rank")
        if row["family"] == "concatenate" and row["op"] != "cat":
            raise ValueError("unsupported native concatenation contract")
        if row["family"] == "binary_pointwise" and (
            policy["vendor"] not in {"nvidia", "thead"}
            or row["op"] != "mul.Tensor"
            or row.get("stub") != "mul_stub"
        ):
            raise ValueError("unsupported native binary pointwise contract")
        if row["family"] == "reduction" and (
            not re.fullmatch(r"[a-z_]+_stub", row.get("stub", ""))
            or row.get("empty") not in {"nan", "zero"}
        ):
            raise ValueError("unsupported reduction contract")
    return policy


def load_policy(vendor="nvidia"):
    return validate_policy(precision_policy(vendor))


def _schema_metadata():
    root = Path(torchgen.__file__).parent / "packaged/ATen/native"
    parsed = parse_native_yaml(
        str(root / "native_functions.yaml"), str(root / "tags.yaml")
    )
    groups = {
        str(group.functional.func.name): group
        for group in get_grouped_native_functions(parsed.native_functions)
        if isinstance(group, NativeFunctionsGroup)
    }
    individual = {
        str(function.func.name): function for function in parsed.native_functions
    }
    return groups, individual, parsed.backend_indices


def schema_groups():
    groups, _, backend_indices = _schema_metadata()
    return groups, backend_indices[DispatchKey.CUDA]


def foreach_metadata(name, individual, backend_indices):
    function = individual.get(name)
    cuda_kernel = (
        backend_indices[DispatchKey.CUDA].get_kernel(function) if function else None
    )
    composite = (
        backend_indices[DispatchKey.CompositeExplicitAutograd].get_kernel(function)
        if function
        else None
    )
    if cuda_kernel is None or cuda_kernel.structured or composite is None:
        raise ValueError(f"missing CUDA or composite foreach implementation: {name}")
    with native_function_manager(function):
        pointer, result, args = unified_sig(function)
    if (
        result not in {"void", "::std::vector<at::Tensor>"}
        or not args
        or args[0] != ("at::TensorList", "self")
        or any(
            kind
            not in {"at::TensorList", "const at::Scalar &", "at::ArrayRef<at::Scalar>"}
            for kind, _ in args
        )
    ):
        raise ValueError(f"unsupported foreach argument/result boundary: {name}")
    return (
        function,
        pointer,
        result,
        args,
        f"{cuda_kernel.cpp_namespace}::{cuda_kernel.kernel}",
        f"{composite.cpp_namespace}::{composite.kernel}",
    )


def render(policy):
    groups, individual, backend_indices = _schema_metadata()
    backend = backend_indices[DispatchKey.CUDA]
    policy_hash = hashlib.sha256(
        json.dumps(policy, sort_keys=True).encode()
    ).hexdigest()
    entries, functions, bindings, headers, catalog = [], [], [], set(), []
    claims, wrappers, core_headers = [], [], set()
    for index, row in enumerate(sorted(policy["operators"], key=lambda r: r["op"])):
        name = row["op"]
        family = row["family"]
        fallback = None
        if family == "foreach":
            function, pointer, result, args, parent, fallback = foreach_metadata(
                name, individual, backend_indices
            )
        else:
            writes_output = family == "softmax_backward_out"
            group = groups.get(name.removesuffix(".out") if writes_output else name)
            if group is None:
                raise ValueError(f"no structured functional schema for {name}")
            metadata = backend.get_kernel(group)
            if metadata is None or not metadata.structured:
                raise ValueError(f"no structured vendor implementation for {name}")
            function = group.out if writes_output else group.functional
            parent = f"{metadata.cpp_namespace}::structured_{metadata.kernel}"
            if family == "binary_pointwise":
                parent = "at::meta::structured_mul_Tensor"
            with native_function_manager(group):
                pointer, result, args = unified_sig(function)
                meta_args = structured.meta_arguments(group)
                impl_args = structured.impl_arguments(group)
            names = [arg_name for _, arg_name in args]
            metadata_inputs = names[:-1] if writes_output else names
            expected_result = "at::Tensor &" if writes_output else "at::Tensor"
            expected_impl = metadata_inputs + [
                arg.name for arg in group.out.func.arguments.out
            ]
            input_type = "const at::Tensor &"
            if family == "concatenate":
                input_type = "const at::ITensorListRef &"
                expected_impl[2:2] = [
                    "valid",
                    "all_contiguous",
                    "all_same_dtype",
                    "all_same_sizes_and_stride",
                    "memory_format",
                ]
            if (
                result != expected_result
                or not args
                or args[0][0] != input_type
                or [arg.name for arg in meta_args] != metadata_inputs
                or [arg.name for arg in impl_args] != expected_impl
            ):
                raise ValueError(
                    f"unsupported structured argument/result boundary: {name}"
                )
        names = [arg_name for _, arg_name in args]
        header = f"ATen/ops/{function.func.name.name.base}_native.h"
        headers.add(header)
        if policy["vendor"] == "nvidia" and name in {
            "sum.dim_IntList",
            "_log_softmax_backward_data",
            "_softmax_backward_data",
        }:
            base = function.func.name.name.base
            fallback = f"at::compositeexplicitautogradnonfunctional::{base}"
            core_headers.add(
                f"ATen/ops/{base}_compositeexplicitautogradnonfunctional_dispatch.h"
            )
        if name == "silu_backward" and policy["vendor"] == "hygon":
            fallback = "at::native::math_silu_backward"
            core_headers.add(header)
        if name == "mul.Tensor" and policy["vendor"] == "thead":
            fallback = "at::compositeexplicitautogradnonfunctional::mul"
            core_headers.update(
                (
                    "ATen/ops/mul_compositeexplicitautogradnonfunctional_dispatch.h",
                    "aten/backends/flagos/thead_vendor_guards.h",
                )
            )
        record = {
            "vendor": policy["vendor"],
            "op": name,
            "schema": str(function.func),
            "pointer": pointer,
            "parent": parent,
            "family": family,
            "dtypes": sorted(row["dtypes"]),
            "policy_sha256": policy_hash,
        }
        if fallback:
            record["composite"] = fallback
        record["abi"] = hashlib.sha256(
            json.dumps(record, sort_keys=True).encode()
        ).hexdigest()
        catalog.append(record)
        fn_type, dispatcher = schema_to_cpp_name(name)
        encoded = json.dumps(json.dumps(record, sort_keys=True, separators=(",", ":")))
        entries.append(
            f'NATIVE_VENDOR_ENTRY("{policy["vendor"]}", {json.dumps(name)}, '
            f"{json.dumps(record['abi'])}, {encoded}, {fn_type}, {dispatcher})"
        )
        arguments = ", ".join(f"{kind} {arg_name}" for kind, arg_name in args)
        call_args = ", ".join(names)
        if fallback:
            claims.append(
                f"  m.impl({json.dumps(name)}, at::native::flagos::NativeVendorFallback_{index});"
            )
            guarded_call = ""
            fallback_call = (
                f"{dispatcher}.DispatchWithFallback(&{fallback}, {call_args})"
            )
            if policy["vendor"] == "thead":
                condition = "kernel"
                if name == "mul.Tensor":
                    condition += f" && thead_vendor::Multiplication({call_args})"
                    fallback_call = f"{fallback}({call_args})"
                guarded_call = (
                    f"  if (auto kernel = {dispatcher}.KernelFor(Backend::kThead); "
                    f"{condition}) {{\n"
                    f"    return kernel({call_args});\n"
                    "  }\n"
                )
            wrappers.append(
                f"static {result} NativeVendorFallback_{index}({arguments}) {{\n"
                f"{guarded_call}"
                f"  return {fallback_call};\n"
                "}\n"
            )
        operand = names[0]
        if family == "foreach":
            lists = ", ".join(name for kind, name in args if kind == "at::TensorList")
            guard = (
                f"  if (!CanBatchForeach<at::ScalarType::BFloat16>({lists}))\n"
                f"    return {fallback}({call_args});\n"
            )
            call = f"{parent}({call_args})"
            operand = "self.front()"
            core_headers.add(header)
        elif family == "concatenate":
            if names != ["tensors", "dim"]:
                raise ValueError(f"unsupported concatenation argument boundary: {name}")
            guard = '  TORCH_CHECK(!tensors.empty(), "torch.cat(): expected a non-empty list of Tensors");\n'
            operand = "tensors.front()"
            call = f"Concatenate<{parent}>({call_args})"
        elif family == "binary_pointwise":
            if names != ["self", "other"]:
                raise ValueError(
                    f"unsupported binary pointwise argument boundary: {name}"
                )
            guard = ""
            operand = "self.is_privateuseone() ? self : other"
            headers.add("ATen/native/BinaryOps.h")
            call = f"BinaryPointwise<{parent}>(at::native::{row['stub']}, {call_args})"
        else:
            admitted = " || ".join(
                f"{operand}.scalar_type() == at::ScalarType::{dtype}"
                for dtype in sorted(row["dtypes"])
            )
            guard = f'  TORCH_CHECK({admitted}, "unmeasured native vendor dtype: {name}");\n'
        if family == "blas":
            if names != ["self", "mat2"]:
                raise ValueError(f"unsupported BLAS argument boundary: {name}")
            call = f"Matrix<{parent}, {row['rank']}>({call_args})"
        elif family == "reduction":
            if names != ["self", "dim", "keepdim", "dtype"]:
                raise ValueError(f"unsupported reduction argument boundary: {name}")
            empty = ", 0.0" if row["empty"] == "zero" else ""
            call = f"Reduction<{parent}>(at::native::{row['stub']}, {call_args}{empty})"
        elif family == "structured":
            call = f"StructuredCall<{parent}>({call_args})"
        elif family == "softmax_backward_out":
            call = f"SoftmaxBackwardOut<{parent}>({call_args})"
        scope = "VendorDeviceScope" if family == "blas" else "VendorScope"
        functions.append(
            f"{result} Entry_{index}({arguments}) {{\n"
            f"{guard}"
            f"  ++hits[{index}];\n"
            f'  RECORD_FUNCTION("flagos::{policy["vendor"]}::{name}", std::vector<c10::IValue>());\n'
            f"  {scope} scope({operand});\n"
            f"  return {call};\n"
            "}\n"
        )
        bindings.append(
            f"  result.append(py::make_tuple({json.dumps(name)}, "
            f"{json.dumps(record['abi'])}, reinterpret_cast<uintptr_t>(&Entry_{index}), "
            f"hits[{index}].load()));"
        )
    if policy["vendor"] == "hygon":
        headers.update(
            ("ATen/ops/to_native.h", "c10/core/InferenceMode.h", "torch/library.h")
        )
    source = (
        BANNER
        + '#include "precision_runtime.h"\n'
        + "".join(f"#include <{header}>\n" for header in sorted(headers))
        + "\nnamespace at::native::flagos::vendor {\n"
        + f"std::atomic<int64_t> hits[{len(catalog)}]{{}};\n"
        + "\n".join(functions)
        + "\npy::list Bindings() {\n  py::list result;\n"
        + "\n".join(bindings)
        + "\n  return result;\n}\n"
        + "}  // namespace at::native::flagos::vendor\n\n"
        + "PYBIND11_MODULE(TORCH_EXTENSION_NAME, module) {\n"
        + '  module.def("bindings", &at::native::flagos::vendor::Bindings);\n'
        + '  module.def("libraries", &at::native::flagos::vendor::Libraries);\n'
        + (
            "  at::native::flagos::vendor::BindStreamScope(module);\n"
            if policy["vendor"] == "hygon"
            else ""
        )
        + "}\n"
    )
    entry_path = ENTRY_PATH
    source_path = SOURCE_DIR / policy["vendor"] / "precision.cc"
    if policy["vendor"] == "hygon":
        entry_path = ENTRY_PATH.with_name("native_vendor_hygon_entries.inc")
        source = "#define FLAGOS_NATIVE_HYGON 1\n" + source + HYGON_TO_DTYPE
    elif policy["vendor"] == "thead":
        entry_path = ENTRY_PATH.with_name("native_vendor_thead_entries.inc")
        source = "#define FLAGOS_NATIVE_THEAD 1\n" + source
    outputs = {
        entry_path: BANNER + "\n".join(entries) + "\n",
        source_path: source,
    }
    if claims:
        registration_path = ENTRY_PATH.with_name(
            f"register_native_vendor_{policy['vendor']}.inc"
        )
        registration = (
            BANNER
            + "#ifdef FLAGOS_GEN_IMPLS\n"
            + "\n".join(claims)
            + "\n#else\n"
            + "".join(f"#include <{header}>\n" for header in sorted(core_headers))
            + "\nnamespace at::native::flagos {\n"
            + "\n".join(wrappers)
            + "}  // namespace at::native::flagos\n"
            + "#endif  // FLAGOS_GEN_IMPLS\n"
        )
        if policy["vendor"] == "thead":
            registration = (
                BANNER
                + "#if defined(FLAGOS_NATIVE_THEAD_VENDOR)\n"
                + registration.removeprefix(BANNER)
                + "#endif  // FLAGOS_NATIVE_THEAD_VENDOR\n"
            )
        outputs[registration_path] = registration
    return outputs, catalog


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--vendor", choices=("nvidia", "hygon", "thead"), default="nvidia"
    )
    parser.add_argument(
        "--print-catalog", action="store_true", help="Emit the build catalog as JSON"
    )
    args = parser.parse_args()
    stale = []
    outputs, catalog = render(load_policy(args.vendor))
    for path, text in outputs.items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check and stale:
        raise SystemExit("stale native vendor entries: " + ", ".join(stale))
    if args.print_catalog:
        print(json.dumps(catalog, indent=2))
    else:
        print(
            "native vendor entries are current"
            if args.check
            else "native vendor entries generated"
        )


if __name__ == "__main__":
    main()
