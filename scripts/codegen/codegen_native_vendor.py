"""Generate typed vendor precision entries from policy and Torch schemas.

Only host metadata and library calls are emitted. Numerical implementations
come from the published vendor libraries. The policy names measured exceptions,
not model shapes or captured paths; all other routes remain unchanged.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import torchgen
from torchgen.api import structured
from torchgen.context import native_function_manager
from torchgen.gen import get_grouped_native_functions, parse_native_yaml
from torchgen.model import DispatchKey, NativeFunctionsGroup

sys.path.insert(0, str(Path(__file__).resolve().parent))
from codegen_ops import schema_to_cpp_name, unified_sig
from native_host_policy import precision_policy

ROOT = Path(__file__).resolve().parents[2]
ENTRY_PATH = ROOT / "csrc/aten/generated/native_vendor_entries.inc"
SOURCE_DIR = ROOT / "csrc/native_host/backends"
BANNER = "// Generated by scripts/codegen/codegen_native_vendor.py. Do not edit.\n"
NVIDIA_HOST_FUNCTIONS = {
    "add.Tensor": ("pointwise", "at::native::add_stub", "Add"),
    "cat": ("concat", "at::native::structured_cat_out_cuda", "Cat"),
    "constant_pad_nd": ("zero_pad", "at::native::constant_pad_nd", "ConstantPadNd"),
    "mul.Tensor": ("pointwise", "at::native::mul_stub", "Mul"),
    "pow.Scalar": ("pointwise", "at::native::structured_pow_Scalar_out", "PowScalar"),
    "sub.Tensor": ("pointwise", "at::native::add_stub", "Sub"),
}
NVIDIA_ATEN_WRAPPERS = {
    "_assert_async": ("AssertAsync", "at::native::_assert_async_cuda"),
    "_assert_async.msg": ("AssertAsyncMessage", "at::native::_assert_async_msg_cuda"),
    "native_layer_norm": ("LayerNorm", "at::native::layer_norm_cuda"),
}
NVIDIA_ATEN_REGISTRATIONS = {
    "_linalg_check_errors": "at::native::_linalg_check_errors",
    "_linalg_solve_ex.result": "SolveExOut",
    "_upsample_nearest_exact2d.out": "UpsampleExactOut",
    "addmm.out": "AddmmOut",
    "equal": "Equal",
    "index.Tensor_out": "IndexOut",
    "index_copy.out": "IndexCopyOut",
    "index_select": "IndexSelect",
    "mul.out": "MulOut",
    "pow.Tensor_Tensor_out": "PowTensorOut",
    "prod.int_out": "ProdIntOut",
}


def render_nvidia_aten(natives):
    """Claim supplemental ATen schemas used by the optional CUDA vendor module."""
    wrappers = []
    registrations = dict(NVIDIA_ATEN_REGISTRATIONS)
    for name, (wrapper, kernel) in NVIDIA_ATEN_WRAPPERS.items():
        native = natives[name]
        with native_function_manager(native):
            _, result, args = unified_sig(native)
        if not args or args[0][0] != "const at::Tensor &":
            raise ValueError(f"unsupported CUDA vendor input: {name}")
        arguments = ", ".join(f"{kind} {arg}" for kind, arg in args)
        operands = ", ".join(arg for _, arg in args)
        wrappers.append(
            f"{result} {wrapper}({arguments}) {{\n"
            f"  VendorScope scope({args[0][1]});\n"
            f"  return {kernel}({operands});\n"
            "}\n"
        )
        registrations[name] = wrapper
    claims = []
    for name, kernel in sorted(registrations.items()):
        if name not in natives:
            raise ValueError(f"unknown CUDA vendor schema: {name}")
        claims.append(f'  m.impl("{name}", {kernel});')
    return (
        BANNER
        + "\n".join(wrappers)
        + "\nTORCH_LIBRARY_IMPL(aten, PrivateUse1, m) {\n"
        + "\n".join(claims)
        + "\n}\n"
    )


def validate_policy(policy):
    if policy.get("schema_version") != 1 or policy.get("vendor") not in {
        "nvidia",
        "hygon",
    }:
        raise ValueError("unsupported vendor precision policy")
    seen = set()
    for row in policy["operators"]:
        if row["op"] in seen:
            raise ValueError(f"duplicate precision exception: {row['op']}")
        seen.add(row["op"])
        if not row.get("reason") or not row.get("dtypes"):
            raise ValueError("precision exceptions require evidence and dtypes")
        family = row["family"]
        admitted = {"Float", "BFloat16"}
        if family == "zero_pad" and policy["vendor"] == "nvidia":
            admitted.update(("Int", "Long"))
        if set(row["dtypes"]) - admitted:
            raise ValueError("unmeasured precision dtype")
        if family not in {"structured", "reduction", "blas", "cudnn_sdpa"}:
            function = NVIDIA_HOST_FUNCTIONS.get(row["op"])
            if (
                policy["vendor"] != "nvidia"
                or function is None
                or family != function[0]
            ):
                raise ValueError("unsupported native vendor family")
        if row["family"] == "cudnn_sdpa" and (
            policy["vendor"] != "nvidia"
            or row["op"] != "scaled_dot_product_attention"
            or row["dtypes"] != ["BFloat16"]
        ):
            raise ValueError("unsupported cuDNN SDPA contract")
        if row["family"] == "blas" and row.get("rank") not in (2, 3):
            raise ValueError("BLAS entries require matrix or batched-matrix rank")
        if row["family"] == "reduction" and (
            not re.fullmatch(r"[a-z_]+_stub", row.get("stub", ""))
            or row.get("empty") != "nan"
        ):
            raise ValueError("unsupported reduction contract")
    return policy


def load_policy(vendor="nvidia"):
    return validate_policy(precision_policy(vendor))


def load_schemas():
    root = Path(torchgen.__file__).parent / "packaged/ATen/native"
    return parse_native_yaml(
        str(root / "native_functions.yaml"), str(root / "tags.yaml")
    )


def schema_groups(parsed=None):
    if parsed is None:
        parsed = load_schemas()
    groups = {
        str(group.functional.func.name): group
        for group in get_grouped_native_functions(parsed.native_functions)
        if isinstance(group, NativeFunctionsGroup)
    }
    return groups, parsed.backend_indices[DispatchKey.CUDA]


def render(policy):
    parsed = load_schemas()
    groups, backend = schema_groups(parsed)
    natives = {str(func.func.name): func for func in parsed.native_functions}
    policy_hash = hashlib.sha256(
        json.dumps(policy, sort_keys=True).encode()
    ).hexdigest()
    entries, functions, bindings, headers, catalog = [], [], [], set(), []
    builtin = []
    for index, row in enumerate(sorted(policy["operators"], key=lambda r: r["op"])):
        name = row["op"]
        is_cudnn = row["family"] == "cudnn_sdpa"
        nvidia_host = (
            NVIDIA_HOST_FUNCTIONS.get(name) if policy["vendor"] == "nvidia" else None
        )
        if is_cudnn:
            functional = natives[name]
            with native_function_manager(functional):
                pointer, result, args = unified_sig(functional)
            if result != "at::Tensor":
                raise ValueError(f"unsupported cuDNN result: {name}")
            parent = "at::native::_cudnn_attention_forward"
            headers.add("backends/nvidia/sdpa.h")
            fn_type, dispatcher = "NvidiaSdpaFn", "nvidia_sdpa_dispatcher"
        elif nvidia_host:
            functional = natives[name]
            with native_function_manager(functional):
                pointer, result, args = unified_sig(functional)
            if result != "at::Tensor":
                raise ValueError(f"unsupported NVIDIA host result: {name}")
            _, parent, _ = nvidia_host
            headers.add("backends/nvidia/tensor_ops.h")
            fn_type, dispatcher = schema_to_cpp_name(name)
        else:
            group = groups.get(name)
            if group is None:
                raise ValueError(f"no structured functional schema for {name}")
            metadata = backend.get_kernel(group)
            if metadata is None or not metadata.structured:
                raise ValueError(f"no structured vendor implementation for {name}")
            functional = group.functional
            with native_function_manager(group):
                pointer, result, args = unified_sig(functional)
                meta_args = structured.meta_arguments(group)
                impl_args = structured.impl_arguments(group)
            names = [arg_name for _, arg_name in args]
            if (
                result != "at::Tensor"
                or not args
                or args[0][0] != "const at::Tensor &"
                or [arg.name for arg in meta_args] != names
                or [arg.name for arg in impl_args] != names + ["out"]
            ):
                raise ValueError(
                    f"unsupported structured argument/result boundary: {name}"
                )
            parent = f"{metadata.cpp_namespace}::structured_{metadata.kernel}"
            headers.add(f"ATen/ops/{functional.func.name.name.base}_native.h")
            fn_type, dispatcher = schema_to_cpp_name(name)
        record = {
            "vendor": policy["vendor"],
            "op": name,
            "schema": str(functional.func),
            "pointer": pointer,
            "parent": parent,
            "family": row["family"],
            "dtypes": sorted(row["dtypes"]),
            "policy_sha256": policy_hash,
        }
        record["abi"] = hashlib.sha256(
            json.dumps(record, sort_keys=True).encode()
        ).hexdigest()
        catalog.append(record)
        encoded = json.dumps(json.dumps(record, sort_keys=True, separators=(",", ":")))
        entries.append(
            f'NATIVE_VENDOR_ENTRY("{policy["vendor"]}", {json.dumps(name)}, '
            f"{json.dumps(record['abi'])}, {encoded}, {fn_type}, {dispatcher})"
        )
        names = [arg_name for _, arg_name in args]
        arguments = ", ".join(f"{kind} {arg_name}" for kind, arg_name in args)
        call_args = ", ".join(names)
        event = f'  RECORD_FUNCTION("flagos::{policy["vendor"]}::{name}", std::vector<c10::IValue>());\n'
        if is_cudnn:
            body = (
                event
                + f"  auto result = CudnnSdpa({call_args});\n"
                + f"  if (result.defined()) ++hits[{index}];\n"
                + "  return result;\n"
            )
        elif nvidia_host:
            _, _, function = nvidia_host
            body = event + f"  ++hits[{index}];\n  return {function}({call_args});\n"
        else:
            if row["family"] == "blas":
                if names != ["self", "mat2"]:
                    raise ValueError(f"unsupported BLAS argument boundary: {name}")
                call = f"Matrix<{parent}, {row['rank']}>({call_args})"
            elif row["family"] == "reduction":
                if names != ["self", "dim", "keepdim", "dtype"]:
                    raise ValueError(f"unsupported reduction argument boundary: {name}")
                call = f"Reduction<{parent}>(at::native::{row['stub']}, {call_args})"
            else:
                call = f"StructuredCall<{parent}>({call_args})"
            scope = "VendorDeviceScope" if row["family"] == "blas" else "VendorScope"
            admitted = " || ".join(
                f"self.scalar_type() == at::ScalarType::{dtype}"
                for dtype in sorted(row["dtypes"])
            )
            body = (
                f'  TORCH_CHECK({admitted}, "unmeasured native vendor dtype: {name}");\n'
                f"  ++hits[{index}];\n"
                + event
                + f"  {scope} scope(self);\n"
                + f"  return {call};\n"
            )
        functions.append(f"at::Tensor Entry_{index}({arguments}) {{\n{body}}}\n")
        bindings.append(
            f"  result.append(py::make_tuple({json.dumps(name)}, "
            f"{json.dumps(record['abi'])}, reinterpret_cast<uintptr_t>(&Entry_{index}), "
            f"hits[{index}].load()));"
        )
        builtin.append(
            f'  RegisterNativeVendorKernel("nvidia", {json.dumps(name)}, '
            f"{json.dumps(record['abi'])}, reinterpret_cast<uintptr_t>(&Entry_{index}));"
        )
    nvidia = policy["vendor"] == "nvidia"
    source = (
        BANNER
        + '#include "precision_runtime.h"\n'
        + (
            '#if defined(FLAGOS_BUILTIN_NVIDIA_PRECISION)\n#include "aten/native_vendor.h"\n#endif\n'
            if nvidia
            else ""
        )
        + "".join(f"#include <{header}>\n" for header in sorted(headers))
        + "\nnamespace at::native::flagos::vendor {\n"
        + f"std::atomic<int64_t> hits[{len(catalog)}]{{}};\n"
        + "\n".join(functions)
        + (
            "\n#if defined(FLAGOS_BUILTIN_NVIDIA_PRECISION)\n"
            "void ActivateNvidiaVendor() {\n" + "\n".join(builtin) + "\n}\n#else\n"
            if nvidia
            else ""
        )
        + "\npy::list Bindings() {\n  py::list result;\n"
        + "\n".join(bindings)
        + "\n  return result;\n}\n"
        + ("#endif\n" if nvidia else "")
        + "}  // namespace at::native::flagos::vendor\n\n"
        + ("#if !defined(FLAGOS_BUILTIN_NVIDIA_PRECISION)\n" if nvidia else "")
        + "PYBIND11_MODULE(TORCH_EXTENSION_NAME, module) {\n"
        + '  module.def("bindings", &at::native::flagos::vendor::Bindings);\n'
        + '  module.def("libraries", &at::native::flagos::vendor::Libraries);\n'
        + (
            "  at::native::flagos::vendor::BindStreamScope(module);\n"
            if policy["vendor"] == "hygon"
            else ""
        )
        + "}\n"
        + ("#endif\n" if nvidia else "")
    )
    entry_path = ENTRY_PATH
    source_path = SOURCE_DIR / policy["vendor"] / "precision.cc"
    if policy["vendor"] == "hygon":
        entry_path = ENTRY_PATH.with_name("native_vendor_hygon_entries.inc")
        source = "#define FLAGOS_NATIVE_HYGON 1\n" + source
    outputs = {
        entry_path: BANNER + "\n".join(entries) + "\n",
        source_path: source,
    }
    if nvidia:
        outputs[source_path.with_name("aten_registration.inc")] = render_nvidia_aten(
            natives
        )
    return outputs, catalog


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--vendor", choices=("nvidia", "hygon"), default="nvidia")
    parser.add_argument(
        "--print-catalog", action="store_true", help="Emit the build catalog as JSON"
    )
    args = parser.parse_args()
    stale = []
    outputs, catalog = render(load_policy(args.vendor))
    for path, text in outputs.items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check and stale:
        raise SystemExit("stale native vendor entries: " + ", ".join(stale))
    if args.print_catalog:
        print(json.dumps(catalog, indent=2))
    else:
        print(
            "native vendor entries are current"
            if args.check
            else "native vendor entries generated"
        )


if __name__ == "__main__":
    main()
