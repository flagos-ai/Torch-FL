def _normalize_flaggems_qualname(fn):
    """Return the runtime-resolved FlagGems entry point for a discovered function.

    ``flag_gems`` re-exports every operator at package level, and that top-level
    name is the one the active backend has already rebound: importing the package
    installs the vendor-specialized callable over the generic one
    (``runtime.backend.SpecOpRegistrar`` writes into the package globals). Taking
    a module path from ``fn.__module__`` instead pins whichever implementation
    that module happens to hold, which on a vendor with overrides is the *generic*
    fallback -- 72 of the 666 kernels generated from the MetaX cohort did exactly
    that, and ``_log_softmax_backward_data`` then failed on hardware with
    ``TypeError: dynamic_func() missing 1 required positional argument:
    'BLOCK_N'`` because the MetaX kernel supplies BLOCK_N through a
    ``triton.heuristics`` decorator that the generic kernel does not carry (its
    ``tune_configs.yaml`` entry lists only BLOCK_M).

    Bare ``flag_gems.<name>`` also drops the vendor alias
    (``_nvidia.ops.mm``, ``gcu300.ops.count_nonzero``, ``_hygon.ops.mul``) that a
    discovery host would otherwise freeze into the artifact. The name is resolved
    against the backend that actually loads the extension, so one generated file
    stays valid on every platform -- the property the previous mapping tried to
    reach by rewriting aliases to ``flag_gems.ops.*``, which is what made the
    generic module the pinned target in the first place.

    Measured over the cohort the checked-in kernels were generated from: all 666
    ``flag_gems.ops.*`` qualnames map to 666 distinct ``flag_gems.<name>`` names,
    every one of which resolves on the package; 594 resolve to the same callable
    as before and 72 to the vendor override. No two distinct qualnames collapse
    onto the same name, and ``PythonOpCache::GetFunc`` already handles the
    one-dot form (``python_op_caller.cc``, dotted branch).
    """
    return f"flag_gems.{fn.__name__}"


def _wrap_quoted(ops, indent: str) -> List[str]:
    """Pack quoted op names into <=79-column lines, matching ruff's output."""
    lines: List[str] = []
    cur = indent
    for op in ops:
        item = f'"{op}",'
        if cur == indent:
            cur = cur + item
        elif len(cur) + 1 + len(item) > 79:
            lines.append(cur)
            cur = indent + item
        else:
            cur = f"{cur} {item}"
    if cur.strip():
        lines.append(cur)
    return lines


def render_flaggems_coverage(ops, excluded) -> Path:
    """Rewrite FLAGGEMS_PYTHON_OPS inside scripts/backend_coverage.py.

    backend_coverage.py calls itself the generated record of this set, but until
    now nothing wrote it: the 482-op literal was a hand-carried snapshot of the
    FlagGems revision CI pinned. Re-running the discovery against a newer flag_gems
    grew the generated kernels while this ceiling stayed put, which silently capped
    every conf built from it -- gen_vendor_confs.py takes FLAGGEMS_PYTHON_OPS as
    the maximum a platform may route to the Python path, so the new ops could never
    reach a conf no matter how many kernels were generated for them.

    ``excluded`` is flaggems_recursive_fallback | flaggems_runtime_broken. Both
    sets name ops whose Python kernel must stay generated but must NOT be a
    default route (unsupported). They are therefore subtracted here: this file is
    the *ceiling* every conf is intersected with, so listing them would make
    gen_vendor_confs.py route them to flagos_python on every platform. They stay
    reachable through FLAGOS_OP_<op>=flagos_python, which is what the retained
    kernels are for.

    Keeping the write here makes the round trip self-consistent: discovery sets the
    ceiling, the ceiling bounds the confs, and test_flaggems_conf_consistency.py
    checks the three against each other.
    """
    ops = sorted(set(ops) - set(excluded))
    body = "\n".join(_wrap_quoted(ops, indent="    "))
    new = f"FLAGGEMS_PYTHON_OPS = frozenset({{\n{body}\n}})  # fmt: skip"
    path = Path(__file__).resolve().parent / "backend_coverage.py"
    patched, n = re.subn(
        r"FLAGGEMS_PYTHON_OPS = frozenset\(\{.*?\}\)  # fmt: skip",
        lambda _: new,
        path.read_text(),
        count=1,
        flags=re.DOTALL,
    )
    if n != 1:
        raise SystemExit(
            f"{path.name}: could not find the FLAGGEMS_PYTHON_OPS block to rewrite"
        )
    path.write_text(patched)
    return path


def discover_flaggems_ops(codegen_ops, funcs):
    """Discover ops that can be safely routed to the FlagGems Python path.

    Returns {op_name: (gems_func_qualname, category, kwargs)} where kwargs is a
    list of (aten_type, name) for trailing aten args that gems declares
    keyword-only and the kernel forwards by name (dtype/alpha/correction/...);
    empty for the common all-positional case.

    Safety gates (see plan; validated in scratch analysis):
      - op must be selected by the caller (op in codegen_ops) and have a schema.
        Selection includes generated dispatchers and manual source-call bridges;
        only the former contributes a backend registration.
      - flag_gems function arity must be inspectable (no *args/**kwargs).
      - category in {functional_pure, inplace, tuple_return, out_variant}, or the
        op is listed in _FLAGGEMS_TENSORLIST_DIM, whose arity gate is the
        stricter "schema is exactly (Tensor[], int) and gems takes both".
      - ARITY gate (guards the silent "dropped trailing scalar" trap):
          functional_pure/inplace/tuple_return: gems npos == #aten args.
          out_variant: gems npos == #aten NON-out args (gems doesn't take `out`).
      - REQUIRED-KEYWORD gate: the arity gates above count positional params
        only, so a gems function with a required keyword-only param would pass
        them and then raise TypeError on every call. An out-variant whose
        required kwonly names match the aten out args is routed via
        out_variant_gemskwout (they are forwarded by name); anything else is
        rejected.
      - every arg passed to the gems function has a generic-caller-covered type.
    """

    try:
        # torch_fl activates the torch.cuda shim (CPU-torch reports no CUDA
        # otherwise), which flag_gems needs at import (get_device_name()). Must
        # run codegen through scripts/vendor/with_nvidia_libtorch.sh so torch_fl imports.
        import torch_fl  # noqa: F401
        import flag_gems
    except Exception as e:
        print(
            f"  [flaggems] import failed ({e}); no python ops discovered",
            file=sys.stderr,
        )
        return {}

    result = {}
    for item in flag_gems._FULL_CONFIG:
        if len(item) < 2:
            continue
        op, fn = item[0], item[1]
        if op in FLAGGEMS_PYTHON_SKIP:
            continue
        if op not in codegen_ops or op not in funcs:
            continue
        # Respect version-condition (item[2]) if present.
        if len(item) > 2 and callable(item[2]) and not item[2]():
            continue
        npos = _flaggems_gems_npos(fn)
        if npos is None:
            # gems wrapper is (*args, **kwargs): arity uninspectable. Accept only
            # hand-verified ops via the explicit override (aten schema is the
            # authoritative arity); everything else stays rejected.
            if op in _FLAGGEMS_ARITY_OVERRIDE:
                npos = _FLAGGEMS_ARITY_OVERRIDE[op]
            else:
                continue
        func = funcs[op]
        cat = detect_category(func)
        if cat not in _FLAGGEMS_PY_CATEGORIES and op not in _FLAGGEMS_TENSORLIST_DIM:
            continue
        s = func.func
        aten_args = list(s.arguments.flat_all)
        # (Tensor[], int) -> Tensor, e.g. cat(tensors, dim). gems takes exactly
        # the schema's two positionals -- no out arg to split off and no
        # trailing kwarg -- so it is decided here, before the branches below,
        # all of which read `cat` as one of the py categories. `kwargs` stays
        # empty: the ListI caller forwards dim positionally.
        if op in _FLAGGEMS_TENSORLIST_DIM:
            schema_types = [str(a.type) for a in aten_args]
            if (
                len(aten_args) == npos == 2
                and schema_types[0] == "Tensor[]"
                and schema_types[1] == "int"
            ):
                result[op] = (_normalize_flaggems_qualname(fn), "tensorlist_dim", [])
            continue
        out_args = list(s.arguments.out) if hasattr(s.arguments, "out") else []
        resolved_cat = cat
        # kwargs: aten trailing args gems declares keyword-only (dtype/alpha/...).
        # Filled by the arity_short branch below; each entry is (name, aten_type).
        kwargs = []
        # *_like factory: functional op whose schema is a source tensor (+ maybe
        # a value positional) followed by TensorOptions + memory_format, all
        # keyword-only in gems. The like_factory caller injects device=flagos/
        # layout/memory_format/pin_memory and forwards dtype; only the non-option
        # positionals are passed. gems reads shape/device from the source tensor.
        if cat == "functional_pure" and op.endswith("_like"):
            all_pairs = [(str(a.type), a.name) for a in aten_args]
            positional = [
                (t, n) for t, n in all_pairs if n not in _FLAGGEMS_LIKE_OPT_FIELDS
            ]
            has_opts = any(n in _FLAGGEMS_LIKE_OPT_FIELDS for _t, n in all_pairs)
            byname = _flaggems_gems_byname_params(fn)
            # gems must accept dtype/layout/device by name and take exactly the
            # non-option positionals (the source tensor, plus full_like's
            # fill_value). npos may exceed via defaulted trailing kwonlys.
            if (
                not has_opts
                or not {"dtype", "layout", "device"} <= byname
                or npos < len(positional)
                or (
                    npos > len(positional)
                    and not _flaggems_extra_trailing_ok(fn, len(positional))
                )
            ):
                continue
            if not all(_flaggems_type_ok(t) for t, _ in positional):
                continue
            qualname = _normalize_flaggems_qualname(fn)
            result[op] = (qualname, "like_factory", positional)
            continue
        # Random in-place: whitelisted inplace op with a trailing Generator? arg.
        # The RandomInplace caller drops the generator positional and injects a
        # CUDA generator by name; only self + scalar positionals are passed.
        if cat == "inplace" and op in _FLAGGEMS_RANDOM_INPLACE:
            all_pairs = [(str(a.type), a.name) for a in aten_args]
            positional = [(t, n) for t, n in all_pairs if t != "Generator?"]
            has_gen = any(t == "Generator?" for t, _n in all_pairs)
            # gems must take exactly self + the scalar params (generator is
            # keyword-only in gems, supplied by name).
            if (
                not has_gen
                or npos < len(positional)
                or (
                    npos > len(positional)
                    and not _flaggems_extra_trailing_ok(fn, len(positional))
                )
            ):
                continue
            if not all(_flaggems_type_ok(t) for t, _ in positional):
                continue
            qualname = _normalize_flaggems_qualname(fn)
            result[op] = (qualname, "random_inplace", positional)
            continue
        # RNG functional with a trailing Generator? the caller can't express:
        # drop it and rely on the philox monkeypatch for RNG state. Routed as
        # functional_pure over the remaining positionals (e.g. multinomial's
        # self, num_samples, replacement); gems takes exactly those.
        if op in _FLAGGEMS_RNG_DROPGEN:
            all_pairs = [(str(a.type), a.name) for a in aten_args]
            positional = [(t, n) for t, n in all_pairs if t != "Generator?"]
            has_gen = any(t == "Generator?" for t, _n in all_pairs)
            if (
                not has_gen
                or npos != len(positional)
                or not all(_flaggems_type_ok(t) for t, _ in positional)
            ):
                continue
            qualname = _normalize_flaggems_qualname(fn)
            result[op] = (qualname, "rng_dropgen", positional)
            continue
        if cat == "factory":
            # Factory: split off the TensorOptions fields (dtype/layout/device/
            # pin_memory); the factory caller injects device=flagos,
            # layout=strided, pin_memory=None and forwards dtype. Only the
            # shape/scalar positionals are passed. Require gems to declare
            # dtype/layout/device by name (kwonly on every gems factory) and its
            # positional count to match the non-option args.
            all_pairs = [(str(a.type), a.name) for a in aten_args]
            positional = [
                (t, n) for t, n in all_pairs if n not in _FLAGGEMS_TENSOROPT_FIELDS
            ]
            has_opts = any(n in _FLAGGEMS_TENSOROPT_FIELDS for _t, n in all_pairs)
            byname = _flaggems_gems_byname_params(fn)
            # gems must accept dtype/layout/device by name, and take exactly the
            # shape/scalar positionals (npos may exceed via a defaulted step, e.g.
            # arange.start's gems has an extra `step` default -> allow >=).
            if (
                not has_opts
                or not {"dtype", "layout", "device"} <= byname
                or npos < len(positional)
                or (
                    npos > len(positional)
                    and not _flaggems_extra_trailing_ok(fn, len(positional))
                )
            ):
                continue
            if not all(_flaggems_type_ok(t) for t, _ in positional):
                continue
            qualname = _normalize_flaggems_qualname(fn)
            result[op] = (qualname, "factory", positional)
            continue
        # Required keyword-only gems params. Every arity gate below counts
        # POSITIONAL params only, so a signature like
        # `sum_out(inp, *, dtype=None, out)` sails through them while the call
        # the codegen emits omits `out` -> TypeError on every invocation.
        #
        # A required kwonly is fine as long as SOMETHING ends up forwarding it,
        # so this is not decided here: it is enforced once at the bottom, after
        # every branch has filled in `kwargs`. That keeps ops the existing kwarg
        # path already covers (sort.stable's required `stable`) working, and
        # only drops the ones nothing supplies. `None` = uninspectable, which no
        # branch can reason about -> reject outright.
        req_kwonly = _flaggems_required_kwonly(fn)
        if req_kwonly is None:
            continue
        out_names = {a.name for a in out_args}
        # Out-variants whose gems out param(s) are required keyword-only and
        # named exactly like the aten out args: forwarded by the kwout branch.
        kwout = cat == "out_variant" and bool(req_kwonly) and req_kwonly <= out_names
        if cat == "out_variant":
            non_out = [(str(a.type), a.name) for a in aten_args if a not in out_args]
            with_out = non_out + [(str(a.type), a.name) for a in out_args]
            if kwout:
                # gems declares the out tensor(s) as REQUIRED keyword-only params
                # (`sum_out(inp, *, dtype=None, out)`, `softmax_backward_out(...,
                # *, grad_input)`) whose names match the aten out args -- checked
                # above. Forward them by name so gems writes into the caller's
                # tensor directly.
                #
                # Only the out args move here; the remaining aten args still have
                # to line up positionally, or be split off by
                # _flaggems_split_kwargs when gems declares them as DEFAULTED
                # keyword-only params (sum_out's `dtype`).
                out_pairs = [(str(a.type), a.name) for a in out_args]
                if npos == len(non_out) or (
                    npos > len(non_out)
                    and _flaggems_extra_trailing_ok(fn, len(non_out), out_names)
                ):
                    passed = non_out
                elif npos < len(non_out):
                    passed, kwargs = _flaggems_split_kwargs(fn, npos, non_out)
                    if passed is None:
                        continue
                else:
                    continue
                kwargs = kwargs + out_pairs
                resolved_cat = "out_variant_gemskwout"
            elif npos == len(non_out) or (
                npos > len(non_out)
                and _flaggems_extra_trailing_ok(fn, len(non_out), out_names)
            ):
                # gems takes only the non-out args (plus optional trailing
                # defaults), returns a fresh tensor; kernel copy_'s it into out.
                passed = non_out
            elif npos == len(with_out) or (
                npos > len(with_out) and _flaggems_extra_trailing_ok(fn, len(with_out))
            ):
                # gems takes `out` positionally and writes into it; pass the out
                # tensor(s) too (plus optional trailing defaults like
                # memory_format=None). Distinguished from the kwout branch above,
                # whose gems out is a required keyword-only param.
                passed = with_out
                resolved_cat = "out_variant_gemsout"
            elif npos < len(non_out):
                passed, kwargs = _flaggems_split_kwargs(fn, npos, non_out)
                if passed is None:
                    continue
            else:
                continue
        else:
            all_args = [(str(a.type), a.name) for a in aten_args]
            if npos == len(all_args) or (
                npos > len(all_args) and _flaggems_extra_trailing_ok(fn, len(all_args))
            ):
                passed = all_args
            elif npos < len(all_args):
                # gems takes fewer positional args: the trailing aten args must be
                # gems keyword-only params, forwarded by name (see kwarg path).
                passed, kwargs = _flaggems_split_kwargs(fn, npos, all_args)
                if passed is None:
                    continue
            else:
                continue
        # Promote ScalarType args out of the positional list into kwargs: the
        # positional caller can't carry a ScalarType (IValue stores it as a plain
        # int), but the by-name kwarg path tags it is_dtype and converts to a
        # torch.dtype. Safe only if gems accepts the arg BY NAME (a param with the
        # same name that isn't positional-only). This recovers ops like
        # _softmax_backward_data / linalg_vector_norm where gems takes dtype as a
        # positional-or-keyword param. See [[flaggems-gap-analysis]] type_gate_dtype.
        promotable = _flaggems_gems_byname_params(fn)
        promote_idx = [
            i
            for i, (t, name) in enumerate(passed)
            if t.startswith("ScalarType") and name in promotable
        ]
        # Only promote if the ScalarType args form a strict SUFFIX of the
        # positional list. Promoting a middle arg would shift the following
        # positionals into gems's dtype slot (wrong). All current ops have dtype
        # last, so this holds; the guard rejects any future middle-dtype op.
        if promote_idx and promote_idx == list(range(promote_idx[0], len(passed))):
            promoted = passed[promote_idx[0] :]
            passed = passed[: promote_idx[0]]
            kwargs = promoted + kwargs
        elif promote_idx:
            continue  # non-suffix ScalarType -> can't safely reorder
        if not all(_flaggems_type_ok(t) for t, _ in passed):
            continue
        if kwargs and not all(t in _FLAGGEMS_KWARG_OK for t, _ in kwargs):
            continue
        # Final required-keyword gate. Now that every branch has settled
        # `kwargs`, demand that each required keyword-only gems param is
        # actually forwarded -- by the kwout branch, by _flaggems_split_kwargs,
        # or by the ScalarType promotion above. Anything left over is a param
        # nothing supplies, so the generated call would raise TypeError the
        # first time the op ran. Drops e.g. gems nonzero_static_out (requires
        # `size` on top of `out`) while keeping sort.stable (required `stable`,
        # already forwarded by name).
        if not req_kwonly <= {name for _t, name in kwargs}:
            continue
        qualname = _normalize_flaggems_qualname(fn)
        result[op] = (qualname, resolved_cat, kwargs)
    return result


def _flaggems_gems_byname_params(fn):
    """Names of gems params that can be passed BY NAME (keyword-only OR
    positional-or-keyword, i.e. anything except positional-only). Used to promote
    a ScalarType positional aten arg into a by-name kwarg the caller can convert
    to a torch.dtype."""
    import inspect

    try:
        params = inspect.signature(fn).parameters.values()
    except (ValueError, TypeError):
        return set()
    return {
        p.name for p in params if p.kind in (p.KEYWORD_ONLY, p.POSITIONAL_OR_KEYWORD)
    }


def _flaggems_split_kwargs(fn, npos, all_passed):
    """For an arity_short op (gems takes `npos` positional args, fewer than the
    `all_passed` aten args), split into (positional, kwargs). The trailing aten
    args beyond `npos` must ALL be gems keyword-only params matched BY NAME, else
    return (None, None) to reject the op (a name mismatch means we can't safely
    forward, and dropping the arg would silently change the result).

    Returns (positional_list, kwarg_list) where each list holds (aten_type, name)
    for positional and (aten_type, name) for kwargs.
    """
    positional = all_passed[:npos]
    trailing = all_passed[npos:]
    kwonly = _flaggems_kwonly_names(fn)
    for _t, name in trailing:
        if name not in kwonly:
            return None, None
    return positional, list(trailing)


def _flaggems_kwarg_cpp(kwargs):
    """Render the C++ `std::vector<PyKwarg>` initializer for the keyword args to
    forward to gems. Each PyKwarg is {name, value, is_dtype, is_none}; a dtype
    (ScalarType) arg is tagged is_dtype so the caller converts it to torch.dtype.
    Optional args (T?) are passed straight through -- the aten C++ arg is a
    std::optional, so a nullopt naturally maps to Python None inside the caller
    only if we mark it; but since we pass the IValue, an absent optional would
    become an int/None ambiguity for dtype. We therefore build the PyKwarg with a
    runtime `.has_value()` check for ScalarType? args."""
    parts = []
    for t, name in kwargs:
        is_dtype = t.startswith("ScalarType")
        if is_dtype:
            if t.endswith("?"):
                # std::optional<ScalarType>: None when absent, else tagged dtype.
                parts.append(
                    f'PyKwarg{{"{name}", {name}.has_value() ? '
                    f"c10::IValue(static_cast<int64_t>(*{name})) : c10::IValue(), "
                    f"/*is_dtype=*/true, /*is_none=*/!{name}.has_value()}}"
                )
            else:
                parts.append(
                    f'PyKwarg{{"{name}", '
                    f"c10::IValue(static_cast<int64_t>({name})), "
                    f"/*is_dtype=*/true}}"
                )
        else:
            # Scalar/int/bool/str/SymInt (and their optionals): IValue can carry
            # these directly. c10::IValue has implicit ctors for each.
            parts.append(f'PyKwarg{{"{name}", {name}}}')
    return "{" + ", ".join(parts) + "}"


def gen_flaggems_python_kernel(
    op,
    fn_type,
    ret_type,
    args,
    gems_func,
    category,
    func,
    kwargs=None,
    *,
    typed=False,
    function_name=None,
):
    """Generate a <Name>KernelPython forwarding to the FlagGems Python op.

    Dispatcher signatures match the generated `*Fn` typedef exactly. Source
    bridges borrow the same argument types and leave result adaptation to their
    existing composite caller. The generic fallback packs the
    aten positional args (faithful order) into a std::vector<c10::IValue> and any
    keyword-only gems args (dtype/alpha/correction/...) into a
    std::vector<PyKwarg>, then calls the generic caller by qualname and adapts
    the result to the category's return convention:
      functional_pure -> UnboxToFlagos(result); return result;
      source_call     -> return the original result without adaptation;
      inplace         -> self.copy_(result); return self;  (or void)
      tuple_return    -> GenericTuple(...); unbox each; return make_tuple(...)
      out_variant     -> Generic/GenericTuple over NON-out args; out_i.copy_(res_i)
    """
    if op in FLAGGEMS_REDUCTION_ADAPTERS:
        gems_func = (
            "torch_fl.compat.flaggems.reductions." + FLAGGEMS_REDUCTION_ADAPTERS[op]
        )
        # These calls use the FlagGems device runtime and supply their own
        # indexed-reduction semantics. They bind no published source host.
        typed = False
    kn = function_name or python_kernel_name(fn_type)
    s = func.func
    aten_args = list(s.arguments.flat_all)
    out_args = list(s.arguments.out) if hasattr(s.arguments, "out") else []
    declarations = []
    cpp_types = {name: t for t, name in args}

    def native_call(
        call, positional, keywords=(), outputs=1, preparation="", types=None
    ):
        if not typed:
            return call
        types = {**cpp_types, **(types or {})}
        arguments = [(types[name], expr, None) for name, expr in positional]
        arguments.extend((types[name], expr, name) for name, expr in keywords)
        declaration, expression = wrap_native_source_call(
            op, gems_func, fn_type + "Source", call, arguments, outputs, preparation
        )
        declarations.append(declaration)
        return expression

    def finish(body, prelude=""):
        if op == "argmin":
            prelude += (
                '  TORCH_CHECK(!self.is_complex(), "argmin(): does not support complex input");\n'
                '  TORCH_CHECK(self.scalar_type() != at::kBool, "argmin(): does not support bool input");\n'
                "  if (dim.has_value()) {\n"
                '    at::native::zero_numel_check_dims(self, at::maybe_wrap_dim(*dim, self.dim()), "argmin()");\n'
                "  } else {\n"
                '    TORCH_CHECK_INDEX(self.numel() != 0, "argmin(): Expected reduction dim to be specified for input.numel() == 0.");\n'
                "  }\n"
            )
        elif op in FLAGGEMS_REDUCTION_ADAPTERS:
            prelude += (
                f'  TORCH_CHECK(!self.is_complex(), "{op.split(".")[0]}(): does not support complex input");\n'
                "  at::native::zero_numel_check_dims(self, at::maybe_wrap_dim(dim, self.dim()), "
                f'"{op.split(".")[0]}()");\n'
            )
        if op in FLAGGEMS_REDUCTION_ADAPTERS:
            # Keep the standard fallback for types the device compiler cannot
            # serve. The shared regression enables strict device execution.
            schema = FLAGGEMS_REDUCTION_ADAPTERS[op]
            prelude += (
                f'  if (FlagGemsRejectsOpDtype("{op}", self.scalar_type())) {{\n'
                f"    return at::native::call_fallback_fn<&cpu_fallback, at::_ops::{schema}>::call(self, dim, keepdim);\n"
                "  }\n"
            )
        if op in FLAGGEMS_HCU_METADATA_ADAPTERS:
            target = FLAGGEMS_HCU_METADATA_ADAPTERS[op]
            prelude += (
                "#if defined(USE_DCU)\n"
                f"  return at::native::flagos::{target}({', '.join(n for _, n in args)});\n"
                "#endif\n"
            )
        if op == "add.Tensor":
            prelude += (
                "#if defined(USE_DCU)\n"
                "  if (!alpha.isIntegral(false))\n"
                "    at::native::alpha_check(at::result_type(self, other), alpha);\n"
                "#endif\n"
            )
        elif op == "mean.dim":
            # FlagGems reduces by dividing by the outer extent, which may be zero.
            prelude += (
                "  if (self.numel() == 0) {\n"
                "    return at::native::call_fallback_fn<&cpu_fallback, at::_ops::mean_dim>::call(self, dim, keepdim, dtype);\n"
                "  }\n"
                "#if defined(USE_DCU)\n"
                "  const auto output_dtype = dtype.value_or(self.scalar_type());\n"
                '  TORCH_CHECK(c10::isFloatingType(output_dtype) || c10::isComplexType(output_dtype), "mean(): input or output dtype must be floating point or complex");\n'
                "#endif\n"
            )
        elif op in ("scatter_add", "scatter_add_"):
            # The FlagGems 2-D kernel reads indices linearly, even when strided.
            prelude += (
                "  if (index.dim() == 2 && !index.is_contiguous()) {\n"
                f"    return at::native::call_fallback_fn<&cpu_fallback, at::_ops::{op}>::call(self, dim, index, src);\n"
                "  }\n"
            )
        elif op == "sort.stable":
            # FlagGems makes the result contiguous even for a transposed
            # input. ATen's sort metadata preserves the dense stride order.
            prelude += (
                "  if (!self.is_contiguous()) {\n"
                "    auto [values, indices] = at::native::call_fallback_fn<&cpu_fallback, at::_ops::sort_stable>::call(self, stable, dim, descending);\n"
                "    const auto strides = self.is_non_overlapping_and_dense() ? self.strides().vec() : at::infer_dense_strides(self.sizes(), self.strides());\n"
                "    auto restore_layout = [&](const at::Tensor& tensor) {\n"
                "      if (tensor.strides().equals(strides)) return tensor;\n"
                "      auto result = at::empty_strided(tensor.sizes(), strides, tensor.options());\n"
                "      result.copy_(tensor);\n"
                "      return result;\n"
                "    };\n"
                "    return {restore_layout(values), restore_layout(indices)};\n"
                "  }\n"
            )
        elif typed and op == "pow.Tensor_Scalar":
            # Match the existing floating-square decomposition while keeping
            # the nested multiply on its configured dispatcher route.
            prelude += (
                "#if defined(USE_DCU)\n"
                "  if (MulTensorFnSource.Available() && c10::isFloatingType(self.scalar_type()) &&\n"
                "      (exponent.isIntegral(false) || exponent.isFloatingPoint()) && exponent.toDouble() == 2.0)\n"
                "    return at::mul(self, self);\n"
                "#endif\n"
            )
        elif op == "cat":
            body = body.replace(
                "  return result;",
                "#if defined(USE_DCU)\n  for (const auto& input : tensors) if (result.is_alias_of(input)) return result.clone();\n#endif\n  return result;",
            )
        return (
            "".join(declarations)
            + f"{ret_type} {kn}({args_decl(args)}) {{\n{prelude}{body}\n}}"
        )

    if category == "factory":
        # Factory: pass only the shape/scalar positionals; the factory caller
        # injects device=flagos/layout=strided/pin_memory=None and forwards
        # dtype + device. `kwargs` here carries the positional (aten_type, name) list.
        positional = kwargs or []
        pos_names = [n for _t, n in positional]
        dtype_name = next((a.name for a in aten_args if a.name == "dtype"), None)
        dtype_expr = dtype_name if dtype_name else "::std::nullopt"
        # Forward the aten `device` arg so the output lands on the requested
        # index. Without it the caller fell back to a hardcoded index 0, which
        # allocated on device 0 while the Triton kernel launched on the current
        # device -- a cross-device write that faults the GPU on multi-card runs.
        device_name = next((a.name for a in aten_args if a.name == "device"), None)
        device_expr = device_name if device_name else "::std::nullopt"
        pos_init = "{" + ", ".join(pos_names) + "}"
        infer = ""
        # arange: gems defaults dtype=None to int64 unconditionally, but aten
        # infers float when ANY of start/end/step is floating. Left alone, gems
        # returns silently-wrong integer values for arange(0.,3.,.5). Replicate
        # aten's rule here so gems always gets an explicit dtype. Only arange has
        # this value-dependent inference; the other factories default to float32,
        # which gems already produces correctly.
        if op.startswith("arange"):
            scalar_names = [n for t, n in positional if "Scalar" in t]
            any_float = " || ".join(f"{n}.isFloatingPoint()" for n in scalar_names)
            infer = (
                f"  ::std::optional<at::ScalarType> _dt = {dtype_expr};\n"
                f"  if (!_dt.has_value()) _dt = ({any_float})\n"
                f"      ? at::typeMetaToScalarType(at::get_default_dtype()) "
                f": at::kLong;\n"
            )
            dtype_expr = "_dt"
        call = (
            f'CallPythonOp_Factory("{gems_func}", '
            f"{pos_init}, {dtype_expr}, {device_expr})"
        )
        call = native_call(
            call,
            [(n, n) for n in pos_names],
            [
                ("dtype", dtype_expr),
                ("device", "_native_target"),
                ("layout", "at::kStrided"),
                ("pin_memory", "std::nullopt"),
            ],
            preparation=f"const auto _native_target = TypedSourceFactoryDevice({device_expr});",
            types={
                "dtype": "std::optional<at::ScalarType>",
                "device": "c10::Device",
                "layout": "at::Layout",
                "pin_memory": "std::nullopt_t",
            },
        )
        body = (
            f"{infer}"
            f"  auto result = {call};\n"
            f"  UnboxToFlagos(result);\n"
            f"  return result;"
        )
        return finish(body)

    if category == "like_factory":
        # *_like: pass the source tensor (+ full_like's fill_value); the caller
        # injects device=flagos/layout/memory_format/pin_memory and forwards
        # dtype (nullopt -> None means "same as self") + device. `kwargs` here
        # carries the non-option positional (aten_type, name) list.
        positional = kwargs or []
        pos_names = [n for _t, n in positional]
        dtype_name = next((a.name for a in aten_args if a.name == "dtype"), None)
        dtype_expr = dtype_name if dtype_name else "::std::nullopt"
        # See the factory branch: forwarded so the result honors the requested
        # device index. nullopt here means "same device as self".
        device_name = next((a.name for a in aten_args if a.name == "device"), None)
        device_expr = device_name if device_name else "::std::nullopt"
        pos_init = "{" + ", ".join(pos_names) + "}"
        call = (
            f'CallPythonOp_LikeFactory("{gems_func}", '
            f"{pos_init}, {dtype_expr}, {device_expr})"
        )
        call = native_call(
            call,
            [(n, n) for n in pos_names],
            [
                ("dtype", dtype_expr),
                ("device", "_native_target"),
                ("layout", "at::kStrided"),
                ("pin_memory", "std::nullopt"),
                ("memory_format", "std::nullopt"),
            ],
            preparation=f"const auto _native_target = TypedSourceFactoryDevice({device_expr}, &{pos_names[0]});",
            types={
                "dtype": "std::optional<at::ScalarType>",
                "device": "c10::Device",
                "layout": "at::Layout",
                "pin_memory": "std::nullopt_t",
                "memory_format": "std::nullopt_t",
            },
        )
        body = f"  auto result = {call};\n  UnboxToFlagos(result);\n  return result;"
        return finish(body)

    if category == "random_inplace":
        # Random in-place: pass self + scalar params (generator dropped); the
        # caller injects a CUDA generator by name. gems writes into self and
        # returns it; copy_ the result back to self for the aten alias contract.
        positional = kwargs or []
        pos_names = [n for _t, n in positional]
        self_name = pos_names[0]
        pos_init = "{" + ", ".join(pos_names) + "}"
        ret_line = "" if ret_type == "void" else f"\n  return {self_name};"
        call = native_call(
            f'CallPythonOp_RandomInplace("{gems_func}", {pos_init})',
            [(n, n) for n in pos_names],
        )
        body = f"  auto result = {call};\n  {self_name}.copy_(result);{ret_line}"
        return finish(body)

    if category == "rng_dropgen":
        # RNG functional with the aten Generator? dropped: pass the remaining
        # positionals to gems; RNG state comes from the philox monkeypatch
        # (compat.flaggems.random.patch_philox). Returns a fresh (flagos) tensor.
        positional = kwargs or []
        pos_names = [n for _t, n in positional]
        pos_init = "{" + ", ".join(pos_names) + "}"
        call = native_call(
            f'CallPythonOp_Generic("{gems_func}", {pos_init})',
            [(n, n) for n in pos_names],
        )
        body = f"  auto result = {call};\n  UnboxToFlagos(result);\n  return result;"
        return finish(body)

    kwargs = kwargs or []
    kw_names = {name for _t, name in kwargs}

    # arg names as they appear in the generated C++ signature. Kwarg-forwarded
    # args are removed from the positional list (they go into the PyKwarg vector).
    if category in ("out_variant", "out_variant_gemskwout"):
        # gemskwout carries its out args in `kwargs`, so the kw_names filter
        # already drops them; the out_args test is what covers plain out_variant.
        passed_names = [
            a.name for a in aten_args if a not in out_args and a.name not in kw_names
        ]
    elif category == "out_variant_gemsout":
        # gems takes the out tensor(s) positionally after the non-out args.
        passed_names = [
            a.name for a in aten_args if a not in out_args and a.name not in kw_names
        ] + [a.name for a in out_args]
    else:
        passed_names = [a.name for a in aten_args if a.name not in kw_names]
    # Widen a contracted axis the platform's triton will not compile, before the
    # operands are packed for the call. See _DOT_CONTRACT_PADDED_OPS.
    native_names = passed_names[:]
    dotpad_lines, dotpad_rename = _dot_contract_prelude(op, args)
    passed_names = [dotpad_rename.get(n, n) for n in passed_names]
    if op == "embedding":
        # sparse only selects the ATen backward representation. The forward
        # gather is identical; FlagGems rejects sparse=True unnecessarily.
        # Autograd retains the original schema argument above this backend.
        passed_names = ["false" if n == "sparse" else n for n in passed_names]
    ivalues = "{" + ", ".join(passed_names) + "}"

    # kwarg call selects the *Kw caller variant; positional-only uses the plain one.
    if kwargs:
        kw_init = _flaggems_kwarg_cpp(kwargs)
        gen_call = f'CallPythonOp_GenericKw("{gems_func}", {ivalues}, {kw_init})'

        def tuple_call(n):
            return (
                f'CallPythonOp_GenericKwTuple("{gems_func}", {ivalues}, {kw_init}, {n})'
            )
    else:
        gen_call = f'CallPythonOp_Generic("{gems_func}", {ivalues})'

        def tuple_call(n):
            return f'CallPythonOp_GenericTuple("{gems_func}", {ivalues}, {n})'

    if category == "source_call":
        # Composite plumbing already owns the device and alias contract. A
        # source call must return the original result without retagging it.
        body = f"  return {gen_call};"
    elif category == "functional_pure":
        body = (
            f"  auto result = {gen_call};\n  UnboxToFlagos(result);\n  return result;"
        )
    elif category == "inplace":
        self_name = passed_names[0]
        ret_line = "" if ret_type == "void" else f"\n  return {self_name};"
        body = f"  auto result = {gen_call};\n  {self_name}.copy_(result);{ret_line}"
    elif category == "tuple_return":
        n = ret_type.count(",") + 1  # ::std::tuple<a,b> -> 2
        unbox = "\n".join(f"  UnboxToFlagos(result[{i}]);" for i in range(n))
        make = ", ".join(f"result[{i}]" for i in range(n))
        body = f"  auto result = {tuple_call(n)};\n{unbox}\n  return {{{make}}};"
    elif category == "out_variant":
        out_names = [a.name for a in out_args]
        if ret_type.startswith("::std::tuple"):
            n = len(out_names)
            copies = "\n".join(
                f"  {out_names[i]}.copy_(result[{i}]);" for i in range(n)
            )
            make = ", ".join(out_names)
            body = f"  auto result = {tuple_call(n)};\n{copies}\n  return {{{make}}};"
        else:
            out_name = out_names[0]
            body = (
                f"  auto result = {gen_call};\n"
                f"  {out_name}.copy_(result);\n"
                f"  return {out_name};"
            )
    elif category == "out_variant_gemsout":
        # gems receives the out tensor(s) positionally and writes into them in
        # place, then returns them; just discard the returned handle and return
        # the aten out arg(s). (Only single-out ops reach here today.)
        out_name = [a.name for a in out_args][0]
        body = f"  {gen_call};\n  return {out_name};"
    elif category == "out_variant_gemskwout":
        # gems declares the out tensor(s) as REQUIRED keyword-only params and
        # writes into them in place (see the kwout branch in
        # discover_flaggems_ops). They are already in `kwargs`, so gen_call
        # forwards them by name; discard the returned handle -- it aliases the
        # very tensor(s) we were handed -- and return the aten out arg(s). No
        # copy_ back: that would be a self-copy.
        out_names = [a.name for a in out_args]
        if len(out_names) == 1:
            call, make = f"  {gen_call};", out_names[0]
        else:
            # median.dim_values / nanmedian.dim_values: gems requires `values`
            # and `indices` by name and returns a namedtuple of both. Use the
            # tuple caller so the sequence return is unpacked rather than run
            # through PythonToTensor, which would reject a non-Tensor.
            call = f"  {tuple_call(len(out_names))};"
            make = "{" + ", ".join(out_names) + "}"
        body = f"{call}\n  return {make};"
    elif category == "tensorlist_dim":
        # (TensorList, int) -> Tensor, e.g. cat(tensors, dim). The dedicated
        # ListI caller materializes the ITensorListRef into a python list and
        # forwards dim positionally, which is the signature gems declares for
        # cat. The two parameter names come from the CppSignature in `args`
        # rather than from the schema: that is what makes the emitted decl match
        # the *Fn typedef it must satisfy, since torchgen spells the schema's
        # `Tensor[]` as `const at::ITensorListRef &` there.
        list_name = next((n for t, n in args if "TensorList" in t), None)
        dim_name = next((n for t, n in args if t in ("int64_t", "int", "long")), None)
        if list_name is None or dim_name is None:
            raise ValueError(
                f"tensorlist_dim needs a TensorList and an integer arg; {op} has {args}"
            )
        body = (
            f'  auto result = CallPythonOp_ListI("{gems_func}", {list_name}, '
            f"{dim_name});\n"
            f"  UnboxToFlagos(result);\n"
            f"  return result;"
        )
    else:
        raise ValueError(f"unsupported flaggems-python category {category} for {op}")

    if category == "tensorlist_dim":
        original_call = f'CallPythonOp_ListI("{gems_func}", {list_name}, {dim_name})'
        replacement = native_call(
            original_call, [(list_name, list_name), (dim_name, dim_name)]
        )
    else:
        outputs = (
            ret_type.count(",") + 1
            if category == "tuple_return"
            else len(out_args)
            if category in ("out_variant", "out_variant_gemskwout")
            and len(out_args) > 1
            else 1
        )
        original_call = tuple_call(outputs) if outputs > 1 else gen_call
        replacement = native_call(
            original_call,
            list(zip(native_names, passed_names)),
            [(name, name) for _, name in kwargs],
            outputs,
        )
    body = body.replace(original_call, replacement)

    # Ordered: the host escape returns before the padding runs, because a dtype
    # this route cannot serve at all should not pay for a pad it will not use.
    host_lines = _host_matmul_prelude(op, args, ret_type)
    return finish(body, host_lines + _native_reduction_prelude(op) + dotpad_lines)


# These out schemas are absent from the published registry. The generated
# adapters preserve ATen output storage while calling the existing functional
# route. No numerical kernel or CUDA redispatch is introduced.
FLAGGEMS_OUT_ADAPTERS = {
    "add.out": "add.Tensor",
    "mul.out": "mul.Tensor",
    "mean.out": "mean.dim",
    "cat.out": "cat",
}
# Reuse the existing ATen metadata primitives. These allocate no device data
# and introduce no numerical implementation or vendor dispatch.
FLAGGEMS_HCU_METADATA_ADAPTERS = {
    "_unsafe_view": "unsafe_view",
    "transpose.int": "transpose_int",
    "unsqueeze": "unsqueeze",
    "slice.Tensor": "slice_tensor",
}
FLAGGEMS_REDUCTION_ADAPTERS = {
    "argmin": "argmin",
    "max.dim": "max_dim",
    "min.dim": "min_dim",
}

_OUT_ADAPTER_MARKER = "// BEGIN GENERATED FLAGGEMS OUT ADAPTERS"


def gen_flaggems_out_adapters(funcs):
    lines = [
        _OUT_ADAPTER_MARKER,
        "#if defined(FLAGOS_FLAGGEMS_PYTHON) && defined(USE_DCU)",
        "#include <ATen/MemoryOverlap.h>",
        "#include <ATen/native/Resize.h>",
        "namespace at::native::flagos {",
    ]
    for op, functional in FLAGGEMS_OUT_ADAPTERS.items():
        out_func, source_func = funcs[op], funcs[functional]

        def signature(func):
            with local.parametrize(
                use_const_ref_for_mutable_tensors=func.use_const_ref_for_mutable_tensors,
                use_ilistref_for_tensor_lists=not should_use_arrayref(func),
            ):
                return unified_sig(func)

        _, result_type, args = signature(out_func)
        _, source_result, source_args = signature(source_func)
        outs = list(out_func.func.arguments.out)
        if len(outs) != 1 or source_result != "at::Tensor":
            raise ValueError("out adapter requires a single functional tensor")
        out_name = outs[0].name
        non_out = [(t, n) for t, n in args if n != out_name]
        if [n for _, n in non_out] != [n for _, n in source_args]:
            raise ValueError(f"out adapter arguments differ: {op}")
        fn_type, dispatcher = schema_to_cpp_name(op)
        _, source_dispatcher = schema_to_cpp_name(functional)
        kernel = fn_type[:-2] + "Adapter"
        lines += [
            f"{result_type} {kernel}({args_decl(args)}) {{",
            f"  at::assert_no_internal_overlap({out_name});",
        ]
        for kind, name in non_out:
            if "TensorList" in kind or "ITensorListRef" in kind:
                lines.append(
                    f"  for (const auto& input : {name}) at::assert_no_overlap({out_name}, input);"
                )
            elif "Tensor" in kind:
                lines.append(f"  at::assert_no_partial_overlap({out_name}, {name});")
        call_args = ", ".join(n for _, n in non_out)
        if op == "mean.out":
            lines.append(
                f'  TORCH_CHECK(!dtype.has_value() || *dtype == {out_name}.scalar_type(), "mean(): dtype must match the output tensor");'
            )
            call_args = call_args.replace(
                "dtype", f"dtype.value_or({out_name}.scalar_type())"
            )
        lines += [
            f"  auto result = {source_dispatcher}({call_args});",
            f'  TORCH_CHECK(result.device() == {out_name}.device(), "out adapter device mismatch");',
            f'  TORCH_CHECK(c10::canCast(result.scalar_type(), {out_name}.scalar_type()), "result type cannot be cast to output type");',
            f"  at::native::resize_output({out_name}, result.sizes());",
            f"  {out_name}.copy_(result);",
            f"  return {out_name};",
            "}",
            f"REGISTER_IMPL_TO_DISPATCHER({fn_type}, {dispatcher}, Backend::kFlagGems, {kernel})",
        ]
    lines += [
        "} // namespace at::native::flagos",
        "#endif",
        "// END GENERATED FLAGGEMS OUT ADAPTERS",
    ]
    return "\n".join(lines) + "\n"


def update_flaggems_out_adapters(path, funcs, *, check=False):
    current = path.read_text()
    refreshed = current
    include = "#include <ATen/native/BinaryOps.h>"
    if include not in refreshed:
        refreshed = refreshed.replace(
            '#include "ops.h"', '#include "ops.h"\n' + include, 1
        )
    metadata_include = '#include "../strided_ops.h"'
    if metadata_include not in refreshed:
        refreshed = refreshed.replace(
            '#include "ops.h"', '#include "ops.h"\n' + metadata_include, 1
        )
    for header in (
        "#include <ATen/ExpandUtils.h>",
        "#include <ATen/native/CPUFallback.h>",
        "#include <ATen/native/ReduceOpsUtils.h>",
        '#include "../fallback.h"',
    ):
        if header not in refreshed:
            refreshed = refreshed.replace(include, include + "\n" + header, 1)
    for op, category, keywords in (
        ("add.Tensor", "functional_pure", {"alpha"}),
        ("mean.dim", "functional_pure", {"dtype"}),
        ("scatter_add", "functional_pure", set()),
        ("scatter_add_", "inplace", set()),
        ("sort.stable", "tuple_return", {"stable", "dim", "descending"}),
        ("cat", "tensorlist_dim", set()),
        ("pow.Tensor_Scalar", "functional_pure", set()),
        *((op, "functional_pure", set()) for op in FLAGGEMS_HCU_METADATA_ADAPTERS),
        ("argmin", "functional_pure", set()),
        ("max.dim", "tuple_return", set()),
        ("min.dim", "tuple_return", set()),
    ):
        func = funcs[op]
        with local.parametrize(
            use_const_ref_for_mutable_tensors=func.use_const_ref_for_mutable_tensors,
            use_ilistref_for_tensor_lists=not should_use_arrayref(func),
        ):
            _, result, args = unified_sig(func)
        fn_type, _ = schema_to_cpp_name(op)
        kwargs = [
            (str(a.type), a.name)
            for a in func.func.arguments.flat_all
            if a.name in keywords
        ]
        host = (
            "flag_gems."
            + {
                "add.Tensor": "add",
                "mean.dim": "mean_dim",
                "scatter_add": "scatter_add",
                "scatter_add_": "scatter_add_",
                "sort.stable": "sort_stable",
                "cat": "cat",
                "pow.Tensor_Scalar": "pow_tensor_scalar",
                "_unsafe_view": "_unsafe_view",
                "transpose.int": "transpose",
                "unsqueeze": "unsqueeze",
                "slice.Tensor": "slice",
                **FLAGGEMS_REDUCTION_ADAPTERS,
            }[op]
        )
        kernel = gen_flaggems_python_kernel(
            op, fn_type, result, args, host, category, func, kwargs, typed=True
        )
        pattern = rf"(?:static TypedSourceSlot {fn_type}Source\([^\n]+\);\n)?{re.escape(result)} {fn_type[:-2]}KernelPython\([^\n]*\) \{{.*?\n\}}"
        refreshed, count = re.subn(pattern, lambda match: kernel, refreshed, flags=re.S)
        if count != 1:
            raise ValueError(f"cannot uniquely refresh the FlagGems adapter for {op}")
    expected = (
        refreshed.split(_OUT_ADAPTER_MARKER, 1)[0].rstrip()
        + "\n\n"
        + gen_flaggems_out_adapters(funcs)
    )
    if check and current != expected:
        raise SystemExit("stale FlagGems out adapters")
    if not check and current != expected:
        path.write_text(expected)


def gen_flaggems_source_bridges(funcs, discovered):
    """Generate source calls for manually registered dispatcher plumbing.

    These functions do not register ATen kernels or change routing. They expose
    the same source-derived ABI to existing composite/device-copy callers, which
    keep their own admission and alias contracts. Discovery and argument mapping
    use exactly the same gates as the generated dispatcher entries.
    """
    declarations, definitions = [], []
    for op in sorted(MANUAL_REGISTERED_OPS & discovered.keys()):
        host, category, kwargs = discovered[op]
        func = funcs[op]
        if category not in ("functional_pure", "inplace") or (
            len(func.func.returns) != 1 or str(func.func.returns[0].type) != "Tensor"
        ):
            continue
        with local.parametrize(
            use_const_ref_for_mutable_tensors=True,
            use_ilistref_for_tensor_lists=not should_use_arrayref(func),
        ):
            _, _, args = unified_sig(func)
        fn_type, _ = schema_to_cpp_name(op)
        name = fn_type[:-2] + "SourceHost"
        declarations.append(f"at::Tensor {name}({args_decl(args)});")
        definitions.append(
            gen_flaggems_python_kernel(
                op,
                fn_type,
                "at::Tensor",
                args,
                host,
                "source_call",
                func,
                kwargs,
                typed=True,
                function_name=name,
            )
        )
    prefix = [
        "// Copyright (c) 2026, BAAI. All rights reserved.",
        "// AUTO-GENERATED by scripts/codegen/codegen_ops.py - DO NOT EDIT",
        "",
    ]
    header = prefix + [
        "#pragma once",
        "#include <ATen/ATen.h>",
        "",
        "namespace at::native::flagos {",
        *declarations,
        "} // namespace at::native::flagos",
    ]
    source = prefix + [
        "#ifdef FLAGOS_FLAGGEMS_PYTHON",
        '#include "flaggems_source_bridges.h"',
        '#include "../backends/flagos/python_op_caller.h"',
        '#include "../backends/flagos/typed_source_host.h"',
        "",
        "namespace at::native::flagos {",
        "\n\n".join(definitions),
        "} // namespace at::native::flagos",
        "#endif // FLAGOS_FLAGGEMS_PYTHON",
    ]
    return "\n".join(header) + "\n", "\n".join(source) + "\n"


# ============================================================================
# Category detection (torchgen metadata)
# ============================================================================


def detect_category(func) -> str:
    s = func.func
    arg_types = [str(a.type) for a in s.arguments.flat_all]

    has_tensorlist = any(t == "Tensor[]" for t in arg_types)
    has_optlist = any("Tensor?[]" in t for t in arg_types)
    has_tensor_in = any(t.startswith("Tensor") and "[]" not in t for t in arg_types)

    # Special case: new_* ops are factory-like (use at::empty + fill)
    op_name = str(s.name.name)
    if op_name.startswith("new_"):
        return "factory"

    if has_optlist:
        return "special_optlist"
    if not has_tensor_in and not has_tensorlist:
        return "factory"
    if has_tensorlist:
        # _foreach_*.out: TensorList out arg, call at::<base>_outf, void return.
        if s.is_out_fn():
            return "foreach_out"
        return "foreach_tensorlist"
    if s.is_out_fn():
        return "out_variant"
    if str(s.kind()).split(".")[-1] == "inplace":
        return "inplace"
    if len(s.returns) > 1:
        return "tuple_return"
    # split.Tensor / unbind.int: single Tensor[] return, no TensorList input.
    if len(s.returns) == 1 and str(s.returns[0].type) == "Tensor[]":
        return "vector_return"
    return "functional_pure"


# ============================================================================
# Authoritative signatures via torchgen (faithful = exploded TensorOptions)
# ============================================================================


def unified_sig(func):
    """
    CppSignature (faithful) for ALL uses: typedef, kernel, and wrapper.
    This ensures the typedef, REGISTER_IMPL, and m.impl all agree on types.

    Faithful = TensorOptions exploded into dtype/layout/device/pin_memory,
    which is exactly what PrivateUse1 boxing dispatch requires.

    Returns (ptr_type_str, ret_type_str, [(cpp_type_str, name), ...]).
    Must be called inside a `with local.parametrize(...)` context.
    """
    from torchgen.api.types import CppSignatureGroup

    group = CppSignatureGroup.from_native_function(
        func, method=False, fallback_binding=False
    )
    sig = (
        group.faithful_signature
        if group.faithful_signature is not None
        else group.signature
    )
    ptr = sig.ptr_type()
    ret_type = ptr.split("(*)", 1)[0].strip()
    args = [(a.type, a.name) for a in sig.arguments()]
    return ptr, ret_type, args


def fn_ptr_signature(ret_type: str, args: List[Tuple[str, str]]) -> str:
    return f"{ret_type} (*)({', '.join(t for t, _ in args)})"


def args_decl(args: List[Tuple[str, str]]) -> str:
    return ", ".join(f"{t} {n}" for t, n in args)


def call_args(args: List[Tuple[str, str]], rename: Dict[str, str] = None) -> str:
    if rename:
        return ", ".join(rename.get(n, n) for _, n in args)
    return ", ".join(n for _, n in args)


def at_api_base(op_name: str) -> str:
    """schema op -> at:: function base name. 'mm.out'->'mm', '_foreach_add_.Scalar'->'_foreach_add_'."""
    return op_name.split(".")[0]


