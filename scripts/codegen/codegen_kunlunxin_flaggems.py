#!/usr/bin/env python3
"""Generate the Kunlunxin FlagGems registration list.

``csrc/aten/backends/kunlunxin/generated/kunlunxin_flaggems_register.inc`` claims
the FlagGems Python ops on PrivateUse1 so that ``backends_kunlunxin.conf`` can
route them to the ``flaggems`` backend. Kunlunxin also has a vendor-native
``kunlunxin_register.inc`` (generated by ``codegen_kunlunxin.py``), so this is one
half of the platform's PrivateUse1 surface: it is disjoint from the native half,
and together they cover every PrivateUse1 registration Kunlunxin has. Without it
a ``flaggems`` route in the conf has no registered slot, and the call reaches the
dispatcher's empty ``kFlagGems`` slot instead of running a kernel.

The list is ``KUNLUNXIN_FLAGGEMS_MEASURED`` (scripts/codegen/gen_vendor_confs.py)
intersected with the platform's FlagGems ceiling. That set is **empty today**: no
P800 overload survey has run yet, so the conf routes nothing to ``flaggems`` and
this file claims nothing. It exists so the PR that measures an op has one value
to edit -- the same value the conf generator reads -- instead of a registration
path to invent. ``gen_vendor_confs.py`` reads this very file as the vendor's
registration set, so the conf and the C++ cannot drift apart.

Deliberately not generated from the shared FlagGems ceiling the way
``codegen_iluvatar_flaggems.py`` is. Iluvatar is in
``FLAGGEMS_PYTHON_PLATFORMS``, which is the statement "this vendor's cohort has
been measured, route the whole ceiling"; Kunlunxin is not, so emitting the ceiling
here would claim ~640 routes the chip has never run -- the false-coverage failure
AGENTS.md's "Default confs never route boxing" section exists to prevent, one
layer down. Kunlunxin joins that set only when its survey lands, and that is a
different PR from this one.

The two .inc files are included into the same PrivateUse1 TORCH_LIBRARY_IMPL body,
so they must be disjoint: a duplicate ``m.impl`` for one op is a compile error,
not a harmless override. An op that is both measured for FlagGems and served by a
native xdnn kernel is therefore a hard error rather than a silent subtraction --
subtracting it would leave the conf routing ``flaggems`` at a slot this file no
longer fills, and the call would die on the empty slot. Moving such an op means
editing the native table in ``codegen_kunlunxin.py`` in the same change.

Usage:
    python3 scripts/codegen/codegen_kunlunxin_flaggems.py            # rewrite the .inc
    python3 scripts/codegen/codegen_kunlunxin_flaggems.py --check    # exit 1 if stale
"""

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gen_vendor_confs as g  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
VENDOR = "kunlunxin"
OUT_INC = REPO / f"csrc/aten/backends/{VENDOR}/generated/{VENDOR}_flaggems_register.inc"
# The CUDA codegen's generated registration: the authoritative op -> Wrapper<Name>
# map. Read directly rather than through codegen_mudnn.wrapper_map(), which drags
# in codegen_ops -> torchgen (a module-level sys.exit without it) and would make
# this generator's --check unrunnable in the lean codegen-checks CI job that its
# siblings run in.
REGISTER_INC = REPO / "csrc/aten/generated/register.inc"


def wrapper_map():
    """op name -> Wrapper<Name>, read back from the CUDA codegen's register.inc."""
    if not REGISTER_INC.exists():
        return {}
    text = REGISTER_INC.read_text()
    return dict(re.findall(r'^\s*m\.impl\("([^"]+)",\s*(\w+)\);', text, re.M))


INC_HEADER = """\
// Copyright (c) 2026, BAAI. All rights reserved.
//
// @generated by scripts/codegen/codegen_kunlunxin_flaggems.py -- DO NOT EDIT.
//
// m.impl() lines for the FlagGems Python ops Kunlunxin routes to the `flaggems`
// backend. Included by register.cc inside TORCH_LIBRARY_IMPL(aten, PrivateUse1)
// when USE_KUNLUNXIN and FLAGOS_FLAGGEMS_PYTHON are set. Kunlunxin also has a
// vendor-native kunlunxin_register.inc (from codegen_kunlunxin.py), so this is
// one half of the platform's PrivateUse1 surface, and the two must stay disjoint:
// an op routed to `flaggems` that is not claimed here reaches the dispatcher with
// an empty kFlagGems slot, and a second m.impl for an op the native half already
// claims is a duplicate registration.
//
// The list is KUNLUNXIN_FLAGGEMS_MEASURED in scripts/codegen/gen_vendor_confs.py,
// intersected with the platform's FlagGems ceiling and minus the native set. That
// set is EMPTY as of this writing: the 640-op FlagGems cohort has not been
// surveyed on the P800, so no route is claimed and this file registers nothing.
// Filling it is the follow-up -- see docs/vendors/kunlunxin/installation.md
// ("FlagGems on Kunlunxin") for the survey invocation and the evidence to record.
//
// Do not hand-edit. Regenerate after changing that set:
//   python3 scripts/codegen/codegen_kunlunxin_flaggems.py
"""


def target_ops() -> list:
    """Sorted op list to register, with the exclusion reasons attached."""
    wrappers = wrapper_map()
    if not wrappers:
        raise SystemExit(
            f"{REGISTER_INC.relative_to(REPO)} is missing or empty; run "
            "scripts/codegen/codegen_ops.py first -- the wrapper symbols are read from it."
        )

    native = g.vendor_native_ops(VENDOR)
    measured = set(g.KUNLUNXIN_FLAGGEMS_MEASURED)
    ceiling = g.flaggems_python_ops_for(VENDOR)

    # The native half wins by default (NATIVE_KERNEL_PREFERRED), but a measured
    # FlagGems route outranks it. Both .inc files live in one TORCH_LIBRARY_IMPL
    # body, so an op in both is a duplicate m.impl -- refuse instead of choosing.
    both = sorted(measured & native)
    if both:
        raise SystemExit(
            "measured for FlagGems but already claimed by the native half: "
            + ", ".join(both)
            + "\nThe two register files are included into one TORCH_LIBRARY_IMPL "
            "body, so a duplicate m.impl will not compile. Remove the op from the "
            "native table in scripts/codegen/codegen_kunlunxin.py in this same "
            "change, then regenerate both .inc files."
        )

    # An op outside the ceiling has no generated wrapper for this platform's
    # runtime, so registering it would name a symbol register.inc does not emit.
    outside = sorted(measured - ceiling)
    if outside:
        raise SystemExit(
            "not in the FlagGems ceiling, so no wrapper exists: "
            + ", ".join(outside)
            + "\nFLAGGEMS_PYTHON_OPS does not cover these; a survey cannot promote "
            "an op FlagGems does not implement."
        )

    unknown = sorted(measured - set(wrappers))
    if unknown:
        raise SystemExit(
            "no generated wrapper for: "
            + ", ".join(unknown)
            + f"\n{REGISTER_INC.relative_to(REPO)} has no m.impl() line for these ops."
        )

    return sorted(measured - native), sorted(native & ceiling)


def render() -> str:
    ops, via_native = target_ops()
    lines = [INC_HEADER]
    lines.append(
        f"// Total: {len(ops)} ops registered here, {len(via_native)} further "
        f"FlagGems ops already claimed by {VENDOR}_register.inc.\n\n"
    )
    wrappers = wrapper_map()
    lines.extend(f'  m.impl("{op}", {wrappers[op]});\n' for op in ops)
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed .inc is stale instead of rewriting it",
    )
    args = ap.parse_args()

    text = render()
    rel = OUT_INC.relative_to(REPO)

    if args.check:
        current = OUT_INC.read_text() if OUT_INC.exists() else ""
        if current != text:
            raise SystemExit(f"{rel} is stale; run: python3 {Path(__file__).name}")
        print(f"[check] {rel} is up to date")
        return

    OUT_INC.parent.mkdir(parents=True, exist_ok=True)
    OUT_INC.write_text(text)
    ops, via_native = target_ops()
    print(f"[gen] {rel}  ({len(ops)} m.impl lines)")
    print(
        f"      {len(via_native)} FlagGems ops already registered by {VENDOR}_register.inc"
    )


if __name__ == "__main__":
    main()
