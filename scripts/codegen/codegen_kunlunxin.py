# sum over an optional dim list. An absent dim list reduces every dim; negative
# dims are wrapped. The concrete-dim overload is used even for the absent case
# so that the vendor's own `optional<std::vector<int64_t>>` (a custom type, not
# std::optional) is never constructed.
#
# Integral inputs accumulate in int64 -- PyTorch's rule, which the vendor
# reduction does not express -- so they take the host round-trip along with any
# dtype outside the vendor scalar-type map. The dtype operand is passed through
# to the vendor as well as used to allocate the output, because the two must
# agree: the output descriptor's declared type is what the vendor writes into.
T_SUM_DIM = """\
at::Tensor {kernel}(
    const at::Tensor& self,
    at::OptionalIntArrayRef dim,
    bool keepdim,
    ::std::optional<at::ScalarType> dtype) {{
  const at::ScalarType out_dtype =
      dtype.has_value() ? dtype.value() : self.scalar_type();
  if (!kunlunxin::{supports}(out_dtype) ||
      at::isIntegralType(self.scalar_type(), /*includeBool=*/true)) {{
    return at::{at_op}(self.cpu(), dim, keepdim, dtype).to(self.device());
  }}

  const int64_t ndim = self.dim();
  std::vector<int64_t> dims = kunlunxin::ToXdnnDims(dim);
  for (int64_t& d : dims) {{
    if (d < 0) {{
      d += ndim;
    }}
  }}
  if (dims.empty()) {{
    for (int64_t d = 0; d < ndim; ++d) {{
      dims.push_back(d);
    }}
  }}
  std::vector<int64_t> out_shape;
  out_shape.reserve(static_cast<size_t>(ndim));
  for (int64_t d = 0; d < ndim; ++d) {{
    const bool reduced = std::find(dims.begin(), dims.end(), d) != dims.end();
    if (reduced) {{
      if (keepdim) {{
        out_shape.push_back(1);
      }}
    }} else {{
      out_shape.push_back(self.size(d));
    }}
  }}

  at::Tensor self_c = self.scalar_type() == out_dtype
      ? self.contiguous()
      : self.to(out_dtype).contiguous();
  kunlunxin::KunlunxinDeviceGuard guard(self_c);
  xpytorch::xpu::api::Context* const context =
      kunlunxin::GetKunlunxinContext(self_c);
  at::Tensor out = at::empty(out_shape, self_c.options());
  kunlunxin::XdnnTensorWrapper t_self(self_c);
  kunlunxin::XdnnTensorWrapper t_out(out);
  KUNLUNXIN_EXEC(
      sum_dim_IntList,
      xdnn_pytorch::sum_dim_IntList(
          context,
          t_self.get(),
          dims,
          keepdim,
          kunlunxin::ToXdnnOptionalDtype(dtype),
          t_out.get()));
  return out;
}}

REGISTER_IMPL_TO_DISPATCHER({fn}, {disp}, Backend::kKunlunxin, {kernel})
"""

# aten's `_softmax` and the vendor's are the same op: the SDK exports
# `_softmax(ctx, self, dim, half_to_float, ret)` directly, so the flag is passed
