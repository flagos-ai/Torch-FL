# The vendor library has no `mm`. `nm -DC` finds only `bmm` and `matmul` in it,
# and `matmul` is the 2-D-capable one, so `mm` composes onto it. The rank-2
# shapes aten's `mm` guarantees are what make the substitution exact.
T_MM = """\
at::Tensor {kernel}(const at::Tensor& self, const at::Tensor& mat2) {{
  const at::ScalarType result_dtype = at::result_type(self, mat2);
  if (!kunlunxin::{supports}(result_dtype)) {{
    return at::{at_op}(self.cpu(), mat2.cpu()).to(self.device());
  }}
  // Matmul entry points in this SDK read their operands strictly, so both are
  // made contiguous rather than described by strides.
  at::Tensor self_c = self.to(result_dtype).contiguous();
  at::Tensor mat2_c = mat2.to(result_dtype).contiguous();
  std::vector<int64_t> out_shape = self_c.sizes().vec();
  out_shape.back() = mat2_c.size(-1);
  kunlunxin::KunlunxinDeviceGuard guard(self_c);
  xpytorch::xpu::api::Context* const context =
      kunlunxin::GetKunlunxinContext(self_c);
  at::Tensor out = at::empty(out_shape, self_c.options());
  kunlunxin::XdnnTensorWrapper t_self(self_c);
  kunlunxin::XdnnTensorWrapper t_mat2(mat2_c);
  kunlunxin::XdnnTensorWrapper t_out(out);
  KUNLUNXIN_EXEC(
      matmul,
      xdnn_pytorch::matmul(context, t_self.get(), t_mat2.get(), t_out.get()));
  return out;
}}

REGISTER_IMPL_TO_DISPATCHER({fn}, {disp}, Backend::kKunlunxin, {kernel})
"""

