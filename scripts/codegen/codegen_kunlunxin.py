def wrapper_map():
    """op name -> Wrapper<Name>, read back from the CUDA codegen's register.inc
    so the m.impl() subset we emit cannot drift from the wrappers that exist."""
    if not REGISTER_INC.exists():
        return {}
    return dict(
        re.findall(
            r'^\s*m\.impl\("([^"]+)",\s*(\w+)\);',
            REGISTER_INC.read_text(),
            flags=re.MULTILINE,
        )
    )


def render():
    """(kernels.cc text, register.inc text, [(op, category)]) for the whole op
    set. Raises on an op with no wrapper, so a stale register.inc fails loudly
    instead of emitting a file that will not link."""
    wrappers = wrapper_map()
    bodies = []
    covered = []
    for op, category in OPS.items():
        wrapper = wrappers.get(op)
        if wrapper is None:
            raise SystemExit(
                f"error: {op} has no wrapper in {REGISTER_INC.relative_to(REPO)}; "
                "run scripts/codegen/codegen_ops.py first"
            )
        fn, disp = schema_to_cpp_name(op)
        kernel = fn[:-2] + "KernelKunlunxin"  # AddTensorFn -> AddTensorKernelKunlunxin
        bodies.append(
            CATEGORIES[category].format(
                kernel=kernel,
                fn=fn,
                disp=disp,
                at_op=AT_OP[op],
                supports=SUPPORTS[category],
                alpha_fallback=", alpha" if op == "add.Tensor" else "",
            )
        )
        covered.append((op, category))

    # Handwritten ops emit an m.impl() line only -- their bodies live in
    # csrc/aten/backends/kunlunxin/rng.cc, not in the generated kernels.cc. They
    # are collected after the OPS loop so an op that is both generated and
    # handwritten is not duplicated.
    for op in sorted(HANDWRITTEN_OPS):
        if op not in wrappers:
            raise SystemExit(
                f"error: handwritten op {op} has no wrapper in "
                f"{REGISTER_INC.relative_to(REPO)}; run "
                "scripts/codegen/codegen_ops.py first"
            )
        if not any(item[0] == op for item in covered):
            covered.append((op, "handwritten"))

    return (
        FILE_HEADER + "\n".join(bodies) + FILE_FOOTER,
        INC_HEADER
        + "".join(f'  m.impl("{op}", {wrappers[op]});\n' for op, _ in sorted(covered)),
        covered,
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the committed artifacts are current instead of writing them",
    )
    args = ap.parse_args()

    cc_text, inc_text, covered = render()

    if args.check:
        stale = []
        for target, text in ((OUT_CC, cc_text), (OUT_INC, inc_text)):
            current = target.read_text() if target.exists() else ""
            if current != text:
                stale.append(target)
        if stale:
            for target in stale:
                print(f"[check] stale: {target.relative_to(REPO)}", file=sys.stderr)
            print(
                "error: run scripts/codegen/codegen_kunlunxin.py to regenerate",
                file=sys.stderr,
            )
            raise SystemExit(1)
        print(f"[check] {len(covered)} kernel(s) up to date")
        return

    OUT_CC.parent.mkdir(parents=True, exist_ok=True)
    OUT_CC.write_text(cc_text)
    OUT_INC.write_text(inc_text)

    print(f"[gen] {OUT_CC.relative_to(REPO)}  ({len(covered)} ops)")
    print(f"[gen] {OUT_INC.relative_to(REPO)}  ({len(covered)} m.impl lines)")
    for op, category in covered:
        print(f"       + {op} [{category}]")


if __name__ == "__main__":
    main()
