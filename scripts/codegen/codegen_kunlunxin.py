# Shared by add/mul. `result_dtype` rather than `other.scalar_type()` is the
# load-bearing detail: a Python number operand arrives as a wrapped scalar
# tensor carrying the number's own dtype (f64 for a float, i64 for an int), and
# promotion deliberately stops it from widening `self`. So for the most ordinary
# spelling there is -- `x * 2.0` -- `other.scalar_type()` is f64 while the
# arithmetic is f32 end to end. Testing at::result_type keeps that operand on
# the fast path instead of declining it into a host round-trip.
#
# The operands are materialised at the common shape rather than handed over
# smaller for the vendor to broadcast: the SDK's broadcast support on these
# entry points is unmeasured here, and an operand the vendor treats as
# un-broadcast is a wrong answer, not a failure. `.expand()` is a view, so the
# copy only happens when the shapes actually differ.
_BINARY_PROLOGUE = """\
  const at::ScalarType result_dtype = at::result_type(self, other);
  if (!kunlunxin::{supports}(result_dtype)) {{
    return at::{at_op}(self.cpu(), other.cpu(){alpha_fallback}).to(self.device());
  }}
  auto self_c = self.scalar_type() == result_dtype ? self : self.to(result_dtype);
  auto other_c = other.device() == self.device() && other.scalar_type() == result_dtype
      ? other : other.to(self.device(), result_dtype);
  const auto sizes = at::infer_size_dimvector(self_c.sizes(), other_c.sizes());
  const at::IntArrayRef out_shape(sizes);
  const auto self_b = (self_c.sizes() == out_shape ? self_c : self_c.expand(out_shape)).contiguous();
  const auto other_b = (other_c.sizes() == out_shape ? other_c : other_c.expand(out_shape)).contiguous();
  kunlunxin::KunlunxinDeviceGuard guard(self_b);
  xpytorch::xpu::api::Context* const context =
      kunlunxin::GetKunlunxinContext(self_b);
  at::Tensor out = at::empty(out_shape, self_b.options());
  kunlunxin::XdnnTensorWrapper t_self(self_b);
  kunlunxin::XdnnTensorWrapper t_other(other_b);
  kunlunxin::XdnnTensorWrapper t_out(out);
"""

