# Generate the Kunlunxin XPU (xdnn_pytorch) operator layer.
#
# Every other vendor codegen in this directory walks the shared op list and
# classifies each op into a category. This one does not: the Kunlunxin backend
# owns a deliberately small, exactly-known set -- the ten ops the
# hardware-agnostic runtime-conformance suite measures
# (tests/integration/runtime/runtime_caps.py RUNTIME_OPS) -- so there is no scan
# to do and each body is written out once, below.
#
# Two consequences worth stating up front:
#
#   * There is no conf writer. torch_fl/configs/backends_kunlunxin.conf is
#     generated by scripts/codegen/gen_vendor_confs.py from the emitted
#     kunlunxin_register.inc (kunlunxin in VENDORS), so the register file is the
#     single hand-off between the two generators and the conf keeps one writer.
#
#   * There is no symbol probe. The vendor entry points are resolved at link
#     time against libxdnn_pytorch.so, and the ten bodies below were written
#     against the header in that SDK (include/xdnn_pytorch/xdnn_pytorch.h), so a
#     call that does not exist is a link error rather than a silently skipped op.
#
# Run it to (re)generate csrc/aten/backends/kunlunxin/generated/; `--check`
# verifies the committed artifacts are current without writing, which is the
# mode CI uses.

