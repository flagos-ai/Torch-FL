# ==========================================================================
# Templates
#
# `{kernel}`, `{fn}` and `{disp}` are filled from schema_to_cpp_name; `{at_op}`
# and `{alpha_fallback}` from AT_OP / this file. Every other brace is C++ and
# is doubled so str.format leaves it alone.
